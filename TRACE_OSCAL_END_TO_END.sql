-- Saved OSCAL only. One joined trace; no RAW fallback and no target writes.
-- Chooses the same MIN saved SSP owner used by the RAW trace. Change no record ID.
-- The final 500-row bound is a display sample, not a complete reconciliation.
-- References are the UNION of saved values across all four Catalog namespaces.
-- Identical references are deduplicated; this does not prove RAW equality or
-- consistency of the reference set across individual saved Catalog placements.
-- Containment is observed from FACT; reference properties retain separate semantics.
WITH
ato_scope AS (
    SELECT MIN(SOURCE_RECORD_ID)::VARCHAR AS ATO_CONTENT_ID
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
    WHERE SOURCE_SYSTEM_NAME = 'ARCHER'
      AND SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
      AND ELEMENT_TYPE = 'implemented-requirements'
),
ssp_found AS (
    SELECT root.SOURCE_RECORD_ID AS ATO_CONTENT_ID,
           ir.PK_OSCAL_SSP_ELEMENT_HASH AS IR_KEY,
           ir.METADATA_JSON:"control-id"::VARCHAR AS SSP_CONTROL_ID,
           ir.METADATA_JSON:props AS IR_PROPS
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT root
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY f1
      ON f1.FK_SOURCE_ELEMENT_HASH = root.PK_OSCAL_SSP_ELEMENT_HASH AND f1.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT ci
      ON ci.PK_OSCAL_SSP_ELEMENT_HASH = f1.FK_TARGET_ELEMENT_HASH AND ci.ELEMENT_TYPE = 'control-implementation'
     AND ci.SOURCE_SYSTEM_NAME = root.SOURCE_SYSTEM_NAME
     AND ci.SOURCE_TABLE_NAME = root.SOURCE_TABLE_NAME AND ci.SOURCE_RECORD_ID = root.SOURCE_RECORD_ID
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_SSP_DEPENDENCY f2
      ON f2.FK_SOURCE_ELEMENT_HASH = ci.PK_OSCAL_SSP_ELEMENT_HASH AND f2.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT ir
      ON ir.PK_OSCAL_SSP_ELEMENT_HASH = f2.FK_TARGET_ELEMENT_HASH AND ir.ELEMENT_TYPE = 'implemented-requirements'
     AND ir.SOURCE_SYSTEM_NAME = root.SOURCE_SYSTEM_NAME
     AND ir.SOURCE_TABLE_NAME = root.SOURCE_TABLE_NAME AND ir.SOURCE_RECORD_ID = root.SOURCE_RECORD_ID
    WHERE root.SOURCE_RECORD_ID = (SELECT ATO_CONTENT_ID FROM ato_scope)
      AND root.SOURCE_SYSTEM_NAME = 'ARCHER' AND root.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
      AND root.ELEMENT_TYPE = 'system-security-plan'
),
scoped_ir AS (
    SELECT ir.PK_OSCAL_SSP_ELEMENT_HASH AS IR_KEY, ir.SOURCE_RECORD_ID AS ATO_CONTENT_ID,
           ir.METADATA_JSON:"control-id"::VARCHAR AS SSP_CONTROL_ID, ir.METADATA_JSON:props AS IR_PROPS
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT ir
    WHERE ir.SOURCE_RECORD_ID = (SELECT ATO_CONTENT_ID FROM ato_scope)
      AND ir.SOURCE_SYSTEM_NAME = 'ARCHER' AND ir.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
      AND ir.ELEMENT_TYPE = 'implemented-requirements'
),
ssp_path_counts AS (
    SELECT IR_KEY, COUNT(*) AS PATH_COUNT FROM ssp_found GROUP BY IR_KEY
),
ssp_path AS (
    -- Enumerate every scoped IR, including an IR missing its expected containing path.
    SELECT s.ATO_CONTENT_ID, i.IR_KEY, i.SSP_CONTROL_ID, i.IR_PROPS, COALESCE(f.PATH_COUNT,0) AS PATH_COUNT
    FROM ato_scope s LEFT JOIN scoped_ir i ON i.ATO_CONTENT_ID = s.ATO_CONTENT_ID
    LEFT JOIN ssp_path_counts f ON f.IR_KEY = i.IR_KEY
),
ir_props AS (
    SELECT i.*, p.value:name::VARCHAR AS PROP_NAME, p.value:ns::VARCHAR AS PROP_NS,
           p.value:value::VARCHAR AS PROP_VALUE
    FROM ssp_path i, LATERAL FLATTEN(INPUT => i.IR_PROPS, OUTER => TRUE) p
),
ir_identity AS (
    SELECT ATO_CONTENT_ID, IR_KEY, SSP_CONTROL_ID, PATH_COUNT,
           COUNT_IF(PROP_NAME = 'archer-content-id' AND PROP_NS IS NULL) AS ALLOCATION_PROP_COUNT,
           -- MIN is used only when exactly one canonical identity property exists.
           IFF(COUNT_IF(PROP_NAME = 'archer-content-id' AND PROP_NS IS NULL) = 1
               AND COUNT(DISTINCT IFF(PROP_NAME = 'archer-content-id' AND PROP_NS IS NULL
                    AND REGEXP_LIKE(PROP_VALUE, '[1-9][0-9]*'), PROP_VALUE, NULL)) = 1,
               MIN(IFF(PROP_NAME = 'archer-content-id' AND PROP_NS IS NULL, PROP_VALUE, NULL)), NULL)
               AS ALLOCATED_CONTROL_CONTENT_ID,
           COUNT_IF(PROP_NAME = 'archer-control-standard-reference' AND PROP_NS = 'urn:archer:source:v1') AS DPF_PROP_COUNT
    FROM ir_props GROUP BY ATO_CONTENT_ID, IR_KEY, SSP_CONTROL_ID, PATH_COUNT
),
dpf_docs AS (
    SELECT IR_KEY, TRY_PARSE_JSON(PROP_VALUE) AS DOC
    FROM ir_props
    WHERE PROP_NAME = 'archer-control-standard-reference' AND PROP_NS = 'urn:archer:source:v1'
),
dpf_refs AS (
    SELECT DISTINCT d.IR_KEY,
           COALESCE(r.value:ContentId::VARCHAR,
                    IFF(TYPEOF(r.value) IN ('INTEGER','DECIMAL','VARCHAR'), r.value::VARCHAR, NULL)) AS REF_ID,
           r.value:LevelId::VARCHAR AS REF_LEVEL, r.value:ModuleId::VARCHAR AS REF_MODULE,
           COALESCE(ARRAY_CONTAINS('LevelId'::VARIANT,OBJECT_KEYS(AS_OBJECT(r.value))),FALSE) AS HAS_LEVEL,
           COALESCE(ARRAY_CONTAINS('ModuleId'::VARIANT,OBJECT_KEYS(AS_OBJECT(r.value))),FALSE) AS HAS_MODULE,
           NOT (r.value IS NULL OR COALESCE(IS_NULL_VALUE(r.value), FALSE)) AS REF_EXISTS
    FROM dpf_docs d,
         LATERAL FLATTEN(INPUT => CASE WHEN TYPEOF(d.DOC) = 'ARRAY' THEN d.DOC
             WHEN d.DOC IS NULL OR COALESCE(IS_NULL_VALUE(d.DOC), FALSE) THEN ARRAY_CONSTRUCT()
             ELSE ARRAY_CONSTRUCT(d.DOC) END, OUTER => TRUE) r
),
dpf AS (
    SELECT *, COALESCE(REGEXP_LIKE(REF_ID, '[1-9][0-9]*'), FALSE)
         AND (NOT HAS_LEVEL OR COALESCE(REF_LEVEL = '41',FALSE))
         AND (NOT HAS_MODULE OR COALESCE(REF_MODULE = '66',FALSE)) AS VALID_REF
    FROM dpf_refs
),
dpf_counts AS (
    SELECT IR_KEY, COUNT(DISTINCT IFF(VALID_REF, REF_ID, NULL)) AS TARGET_COUNT,
           COUNT_IF(REF_EXISTS AND NOT VALID_REF) AS INVALID_COUNT
    FROM dpf GROUP BY IR_KEY
),
cat AS (
    SELECT * FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT
    WHERE SOURCE_SYSTEM_NAME = 'ARCHER' AND SOURCE_TABLE_NAME IN (
        'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW',
        'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_1_RAW',
        'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW',
        'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW')
),
control_identity AS (
    SELECT c.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS CONTROL_KEY,
           MIN(IFF(cid.value:name::VARCHAR = 'archer-content-id' AND cid.value:ns IS NULL,
                   cid.value:value::VARCHAR,NULL)) AS STANDARD_ID
    FROM cat c, LATERAL FLATTEN(INPUT => c.METADATA_JSON:props,OUTER => TRUE) cid
    WHERE c.ELEMENT_TYPE = 'controls'
    GROUP BY c.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
    HAVING COUNT_IF(cid.value:name::VARCHAR = 'archer-content-id' AND cid.value:ns IS NULL) = 1
       AND COUNT_IF(cid.value:name::VARCHAR = 'archer-content-id' AND cid.value:ns IS NULL
                    AND REGEXP_LIKE(cid.value:value::VARCHAR,'[1-9][0-9]*')) = 1
),
standard_controls AS (
    SELECT DISTINCT c.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS CONTROL_KEY,
           c.SOURCE_TABLE_NAME, c.SOURCE_RECORD_ID AS CATALOG_ID, i.STANDARD_ID,
           c.METADATA_JSON:title::VARCHAR AS STANDARD_NAME, c.METADATA_JSON
    FROM cat c JOIN control_identity i ON i.CONTROL_KEY = c.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
    WHERE c.ELEMENT_TYPE = 'controls'
),
standard_names AS (
    SELECT DISTINCT STANDARD_ID, STANDARD_NAME FROM standard_controls
),
standard_counts AS (
    SELECT STANDARD_ID, COUNT(DISTINCT CONTROL_KEY) AS PLACEMENTS,
           COUNT(DISTINCT STANDARD_NAME) AS NAME_VARIANTS
    FROM standard_controls GROUP BY STANDARD_ID
),
base AS (
    SELECT DISTINCT i.*, IFF(d.VALID_REF, d.REF_ID, NULL) AS CONTROL_STANDARD_CONTENT_ID,
           n.STANDARD_NAME AS CONTROL_STANDARD_NAME,
           COALESCE(dc.TARGET_COUNT, 0) AS DPF_TARGET_COUNT,
           COALESCE(dc.INVALID_COUNT, 0) AS INVALID_DPF_COUNT,
           COALESCE(sc.PLACEMENTS, 0) AS STANDARD_PLACEMENTS,
           COALESCE(sc.NAME_VARIANTS, 0) AS STANDARD_NAME_VARIANTS
    FROM ir_identity i
    LEFT JOIN dpf d ON d.IR_KEY = i.IR_KEY
    LEFT JOIN dpf_counts dc ON dc.IR_KEY = i.IR_KEY
    LEFT JOIN standard_counts sc ON sc.STANDARD_ID = d.REF_ID AND d.VALID_REF
    LEFT JOIN standard_names n ON n.STANDARD_ID = d.REF_ID AND d.VALID_REF
),
standard_prop_docs AS (
    SELECT DISTINCT c.STANDARD_ID,
           IFF(p.value:name::VARCHAR = 'policy-hierarchy-level-1-2-3', 'POLICY', 'AUTHORITATIVE') AS KIND,
           TRY_PARSE_JSON(p.value:value::VARCHAR) AS DOC,
           p.value:value::VARCHAR IS NOT NULL AND TRIM(p.value:value::VARCHAR) NOT IN ('','null') AS HAS_VALUE
    FROM standard_controls c, LATERAL FLATTEN(INPUT => c.METADATA_JSON:props) p
    WHERE p.value:ns::VARCHAR = 'urn:archer:source:v1'
      AND p.value:name::VARCHAR IN ('policy-hierarchy-level-1-2-3','authoritative-sources')
),
standard_refs AS (
    SELECT DISTINCT d.STANDARD_ID, d.KIND,
           COALESCE(r.value:ContentId::VARCHAR,
                    IFF(TYPEOF(r.value) IN ('INTEGER','DECIMAL','VARCHAR'), r.value::VARCHAR, NULL)) AS REF_ID,
           r.value:LevelId::VARCHAR AS REF_LEVEL, r.value:ModuleId::VARCHAR AS REF_MODULE,
           COALESCE(ARRAY_CONTAINS('LevelId'::VARIANT,OBJECT_KEYS(AS_OBJECT(r.value))),FALSE) AS HAS_LEVEL,
           COALESCE(ARRAY_CONTAINS('ModuleId'::VARIANT,OBJECT_KEYS(AS_OBJECT(r.value))),FALSE) AS HAS_MODULE,
           (NOT (r.value IS NULL OR COALESCE(IS_NULL_VALUE(r.value), FALSE))
             OR (d.DOC IS NULL AND d.HAS_VALUE)) AS REF_EXISTS
    FROM standard_prop_docs d,
         LATERAL FLATTEN(INPUT => CASE WHEN TYPEOF(d.DOC) = 'ARRAY' THEN d.DOC
             WHEN d.DOC IS NULL OR COALESCE(IS_NULL_VALUE(d.DOC), FALSE) THEN ARRAY_CONSTRUCT()
             ELSE ARRAY_CONSTRUCT(d.DOC) END, OUTER => TRUE) r
),
policy_groups AS (
    SELECT DISTINCT g.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS GROUP_KEY,
           root.SOURCE_RECORD_ID AS POLICY_ID,
           CASE root.SOURCE_TABLE_NAME WHEN 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_1_RAW' THEN 3
                WHEN 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW' THEN 4 ELSE 5 END AS POLICY_LEVEL,
           g.METADATA_JSON:title::VARCHAR AS POLICY_NAME
    FROM cat root
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f ON f.FK_SOURCE_ELEMENT_HASH = root.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
      AND f.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN cat g ON g.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH = f.FK_TARGET_ELEMENT_HASH
      AND g.ELEMENT_TYPE = 'groups' AND g.SOURCE_TABLE_NAME = root.SOURCE_TABLE_NAME
      AND g.SOURCE_RECORD_ID = root.SOURCE_RECORD_ID
    WHERE root.ELEMENT_TYPE = 'catalog'
      AND root.SOURCE_TABLE_NAME IN ('ARCHER_CONTENT_POLICIES_POLICY_LEVEL_1_RAW',
          'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW','ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW')
),
policy_docs AS (
    SELECT DISTINCT POLICY_ID,POLICY_LEVEL,POLICY_NAME FROM policy_groups
),
policy_name_counts AS (
    SELECT POLICY_ID, POLICY_LEVEL, COUNT(*) AS NAME_VARIANTS
    FROM policy_docs GROUP BY POLICY_ID, POLICY_LEVEL
),
parent_docs AS (
    SELECT DISTINCT p.SOURCE_RECORD_ID AS OWNER_ID,
           IFF(p.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW', 5, 4) AS OWNER_LEVEL,
           IFF(p.METADATA_JSON:name::VARCHAR = 'policy-level-2-reference', 4, 3) AS PARENT_LEVEL,
           TRY_PARSE_JSON(p.METADATA_JSON:value::VARCHAR) AS DOC,
           p.METADATA_JSON:value::VARCHAR IS NOT NULL
             AND TRIM(p.METADATA_JSON:value::VARCHAR) NOT IN ('','null') AS HAS_VALUE
    FROM cat p
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f ON f.FK_TARGET_ELEMENT_HASH = p.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
      AND f.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN policy_groups g ON g.GROUP_KEY = f.FK_SOURCE_ELEMENT_HASH AND g.POLICY_ID = p.SOURCE_RECORD_ID
      AND g.POLICY_LEVEL = IFF(p.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW',5,4)
    WHERE p.ELEMENT_TYPE = 'props' AND p.METADATA_JSON:ns::VARCHAR = 'urn:archer:source:v1'
      AND ((p.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW'
            AND p.METADATA_JSON:name::VARCHAR = 'policy-level-2-reference')
        OR (p.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW'
            AND p.METADATA_JSON:name::VARCHAR = 'policy-level-1-reference'))
),
parent_ref_values AS (
    SELECT DISTINCT d.OWNER_ID, d.OWNER_LEVEL, d.PARENT_LEVEL,
           COALESCE(r.value:ContentId::VARCHAR,
                    IFF(TYPEOF(r.value) IN ('INTEGER','DECIMAL','VARCHAR'), r.value::VARCHAR, NULL)) AS PARENT_ID,
           r.value:LevelId::VARCHAR AS DECLARED_LEVEL, r.value:ModuleId::VARCHAR AS DECLARED_MODULE,
           COALESCE(ARRAY_CONTAINS('LevelId'::VARIANT,OBJECT_KEYS(AS_OBJECT(r.value))),FALSE) AS HAS_LEVEL,
           COALESCE(ARRAY_CONTAINS('ModuleId'::VARIANT,OBJECT_KEYS(AS_OBJECT(r.value))),FALSE) AS HAS_MODULE,
           (NOT (r.value IS NULL OR COALESCE(IS_NULL_VALUE(r.value), FALSE))
             OR (d.DOC IS NULL AND d.HAS_VALUE)) AS REF_EXISTS
    FROM parent_docs d,
         LATERAL FLATTEN(INPUT => CASE WHEN TYPEOF(d.DOC) = 'ARRAY' THEN d.DOC
             WHEN d.DOC IS NULL OR COALESCE(IS_NULL_VALUE(d.DOC), FALSE) THEN ARRAY_CONSTRUCT()
             ELSE ARRAY_CONSTRUCT(d.DOC) END, OUTER => TRUE) r
),
parent_refs AS (
    SELECT *, COALESCE(REGEXP_LIKE(PARENT_ID, '[1-9][0-9]*'), FALSE)
        AND (NOT HAS_LEVEL OR COALESCE(DECLARED_LEVEL = PARENT_LEVEL::VARCHAR,FALSE))
        AND (NOT HAS_MODULE OR COALESCE(DECLARED_MODULE = '65',FALSE)) AS VALID_REF
    FROM parent_ref_values
),
parent_counts AS (
    SELECT OWNER_ID, OWNER_LEVEL,
           COUNT(DISTINCT IFF(VALID_REF, PARENT_ID, NULL)) AS PARENT_COUNT,
           COUNT_IF(REF_EXISTS AND NOT VALID_REF) AS INVALID_COUNT
    FROM parent_refs GROUP BY OWNER_ID, OWNER_LEVEL
),
policy_start AS (
    SELECT b.*, r.REF_ID AS POLICY_REF_ID, r.REF_LEVEL, r.REF_MODULE, r.REF_EXISTS,
           COALESCE(TRY_TO_NUMBER(r.REF_LEVEL), p.POLICY_LEVEL) AS START_LEVEL,
           p.POLICY_ID AS RESOLVED_POLICY_ID, p.POLICY_NAME,
           COALESCE(nc.NAME_VARIANTS, 0) AS POLICY_NAME_VARIANTS,
           COALESCE(REGEXP_LIKE(r.REF_ID, '[1-9][0-9]*'), FALSE)
             AND (NOT r.HAS_LEVEL OR COALESCE(r.REF_LEVEL IN ('3','4','5'),FALSE))
             AND (NOT r.HAS_MODULE OR COALESCE(r.REF_MODULE = '65',FALSE)) AS VALID_POLICY_REF
    FROM base b
    LEFT JOIN standard_refs r ON r.STANDARD_ID = b.CONTROL_STANDARD_CONTENT_ID AND r.KIND = 'POLICY'
    LEFT JOIN policy_docs p ON p.POLICY_ID = r.REF_ID
      AND (NOT r.HAS_LEVEL OR COALESCE(r.REF_LEVEL = p.POLICY_LEVEL::VARCHAR,FALSE))
      AND (NOT r.HAS_MODULE OR COALESCE(r.REF_MODULE = '65',FALSE))
    LEFT JOIN policy_name_counts nc ON nc.POLICY_ID = p.POLICY_ID AND nc.POLICY_LEVEL = p.POLICY_LEVEL
),
policy_paths AS (
    SELECT p.*,
           IFF(p.START_LEVEL = 5, p.POLICY_REF_ID, NULL) AS L3_ID,
           IFF(p.START_LEVEL = 5, p.POLICY_NAME, NULL) AS L3_NAME,
           CASE WHEN p.START_LEVEL = 4 THEN p.POLICY_REF_ID WHEN p.START_LEVEL = 5 THEN r2.PARENT_ID END AS L2_ID,
           CASE WHEN p.START_LEVEL = 4 THEN p.POLICY_NAME WHEN p.START_LEVEL = 5 THEN d2.POLICY_NAME END AS L2_NAME,
           CASE WHEN p.START_LEVEL = 3 THEN p.POLICY_REF_ID ELSE r1.PARENT_ID END AS L1_ID,
           CASE WHEN p.START_LEVEL = 3 THEN p.POLICY_NAME ELSE d1.POLICY_NAME END AS L1_NAME,
           COALESCE(c2.PARENT_COUNT,0) AS L2_PARENT_COUNT, COALESCE(c1.PARENT_COUNT,0) AS L1_PARENT_COUNT,
           COALESCE(c2.INVALID_COUNT,0) + COALESCE(c1.INVALID_COUNT,0) AS INVALID_PARENT_COUNT,
           IFF(r2.PARENT_ID IS NOT NULL AND d2.POLICY_ID IS NULL,1,0)
             + IFF(r1.PARENT_ID IS NOT NULL AND d1.POLICY_ID IS NULL,1,0) AS MISSING_PARENT_COUNT,
           GREATEST(COALESCE(n2.NAME_VARIANTS,0),COALESCE(n1.NAME_VARIANTS,0)) AS ANCESTOR_NAME_VARIANTS
    FROM policy_start p
    LEFT JOIN parent_refs r2 ON p.START_LEVEL = 5 AND r2.OWNER_ID = p.POLICY_REF_ID
      AND r2.OWNER_LEVEL = 5 AND r2.PARENT_LEVEL = 4 AND r2.VALID_REF
    LEFT JOIN parent_counts c2 ON p.START_LEVEL = 5 AND c2.OWNER_ID = p.POLICY_REF_ID AND c2.OWNER_LEVEL = 5
    LEFT JOIN policy_docs d2 ON d2.POLICY_ID = r2.PARENT_ID AND d2.POLICY_LEVEL = 4
    LEFT JOIN policy_name_counts n2 ON n2.POLICY_ID = d2.POLICY_ID AND n2.POLICY_LEVEL = 4
    LEFT JOIN parent_refs r1 ON r1.OWNER_ID = CASE WHEN p.START_LEVEL = 5 THEN r2.PARENT_ID
                                             WHEN p.START_LEVEL = 4 THEN p.POLICY_REF_ID END
      AND r1.OWNER_LEVEL = 4 AND r1.PARENT_LEVEL = 3 AND r1.VALID_REF
    LEFT JOIN parent_counts c1 ON c1.OWNER_ID = CASE WHEN p.START_LEVEL = 5 THEN r2.PARENT_ID
                                                  WHEN p.START_LEVEL = 4 THEN p.POLICY_REF_ID END AND c1.OWNER_LEVEL = 4
    LEFT JOIN policy_docs d1 ON d1.POLICY_ID = r1.PARENT_ID AND d1.POLICY_LEVEL = 3
    LEFT JOIN policy_name_counts n1 ON n1.POLICY_ID = d1.POLICY_ID AND n1.POLICY_LEVEL = 3
),
source_metadata AS (
    SELECT DISTINCT root.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS SOURCE_KEY,
           md.METADATA_JSON:title::VARCHAR AS SOURCE_NAME
    FROM cat root
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f ON f.FK_SOURCE_ELEMENT_HASH = root.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
      AND f.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN cat md ON md.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH = f.FK_TARGET_ELEMENT_HASH
      AND md.ELEMENT_TYPE = 'metadata' AND md.SOURCE_TABLE_NAME = root.SOURCE_TABLE_NAME
      AND md.SOURCE_RECORD_ID = root.SOURCE_RECORD_ID
    WHERE root.ELEMENT_TYPE = 'catalog' AND root.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'
),
source_roots AS (
    SELECT DISTINCT root.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS SOURCE_KEY,
           root.SOURCE_RECORD_ID AS SOURCE_ID, md.SOURCE_NAME
    FROM cat root LEFT JOIN source_metadata md ON md.SOURCE_KEY = root.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
    WHERE root.ELEMENT_TYPE = 'catalog' AND root.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'
),
group_identity AS (
    SELECT g.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS GROUP_KEY,
           MIN(IFF(cid.value:name::VARCHAR = 'archer-content-id' AND cid.value:ns IS NULL,
                   cid.value:value::VARCHAR,NULL)) AS GROUP_CONTENT_ID
    FROM cat g, LATERAL FLATTEN(INPUT => g.METADATA_JSON:props,OUTER => TRUE) cid
    WHERE g.ELEMENT_TYPE = 'groups' AND g.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'
    GROUP BY g.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
    HAVING COUNT_IF(cid.value:name::VARCHAR = 'archer-content-id' AND cid.value:ns IS NULL) = 1
       AND COUNT_IF(cid.value:name::VARCHAR = 'archer-content-id' AND cid.value:ns IS NULL
                    AND REGEXP_LIKE(cid.value:value::VARCHAR,'[1-9][0-9]*')) = 1
),
hierarchy_groups AS (
    SELECT DISTINCT g.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS GROUP_KEY, g.SOURCE_RECORD_ID AS SOURCE_ID,
           i.GROUP_CONTENT_ID, g.METADATA_JSON:title::VARCHAR AS GROUP_NAME
    FROM cat g JOIN group_identity i ON i.GROUP_KEY = g.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
    WHERE g.ELEMENT_TYPE = 'groups' AND g.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'
),
topics AS (
    SELECT DISTINCT s.*, g.GROUP_KEY AS TOPIC_KEY, g.GROUP_CONTENT_ID AS TOPIC_ID, g.GROUP_NAME AS TOPIC_NAME
    FROM source_roots s JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f ON f.FK_SOURCE_ELEMENT_HASH = s.SOURCE_KEY AND f.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN hierarchy_groups g ON g.GROUP_KEY = f.FK_TARGET_ELEMENT_HASH AND g.SOURCE_ID = s.SOURCE_ID
),
sections AS (
    SELECT DISTINCT t.*, g.GROUP_KEY AS SECTION_KEY, g.GROUP_CONTENT_ID AS SECTION_ID, g.GROUP_NAME AS SECTION_NAME
    FROM topics t JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f ON f.FK_SOURCE_ELEMENT_HASH = t.TOPIC_KEY AND f.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN hierarchy_groups g ON g.GROUP_KEY = f.FK_TARGET_ELEMENT_HASH AND g.SOURCE_ID = t.SOURCE_ID
),
subsections AS (
    SELECT DISTINCT s.*, g.GROUP_CONTENT_ID AS SUBSECTION_ID, g.GROUP_NAME AS SUBSECTION_NAME
    FROM sections s JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f ON f.FK_SOURCE_ELEMENT_HASH = s.SECTION_KEY AND f.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN hierarchy_groups g ON g.GROUP_KEY = f.FK_TARGET_ELEMENT_HASH AND g.SOURCE_ID = s.SOURCE_ID
),
authority_targets AS (
    SELECT SOURCE_ID AS TARGET_ID, 6 AS TARGET_LEVEL, SOURCE_ID, SOURCE_NAME,
           NULL::VARCHAR AS TOPIC_ID,NULL::VARCHAR AS TOPIC_NAME,NULL::VARCHAR AS SECTION_ID,NULL::VARCHAR AS SECTION_NAME,
           NULL::VARCHAR AS SUBSECTION_ID,NULL::VARCHAR AS SUBSECTION_NAME FROM source_roots
    UNION
    SELECT TOPIC_ID,7,SOURCE_ID,SOURCE_NAME,TOPIC_ID,TOPIC_NAME,NULL,NULL,NULL,NULL FROM topics
    UNION
    SELECT SECTION_ID,8,SOURCE_ID,SOURCE_NAME,TOPIC_ID,TOPIC_NAME,SECTION_ID,SECTION_NAME,NULL,NULL FROM sections
    UNION
    SELECT SUBSECTION_ID,9,SOURCE_ID,SOURCE_NAME,TOPIC_ID,TOPIC_NAME,SECTION_ID,SECTION_NAME,SUBSECTION_ID,SUBSECTION_NAME FROM subsections
),
authority_paths AS (
    SELECT b.*, r.REF_ID AS AUTH_REF_ID, r.REF_LEVEL, r.REF_MODULE, r.REF_EXISTS,
           a.*, COUNT(a.TARGET_ID) OVER (PARTITION BY b.IR_KEY,b.CONTROL_STANDARD_CONTENT_ID,
               b.CONTROL_STANDARD_NAME,r.REF_ID,r.REF_LEVEL,r.REF_MODULE) AS SAVED_PATH_COUNT,
           COALESCE(REGEXP_LIKE(r.REF_ID,'[1-9][0-9]*'),FALSE)
             AND (NOT r.HAS_LEVEL OR COALESCE(r.REF_LEVEL IN ('6','7','8','9'),FALSE))
             AND (NOT r.HAS_MODULE OR COALESCE(r.REF_MODULE = '67',FALSE)) AS VALID_AUTH_REF
    FROM base b
    LEFT JOIN standard_refs r ON r.STANDARD_ID = b.CONTROL_STANDARD_CONTENT_ID AND r.KIND = 'AUTHORITATIVE'
    LEFT JOIN authority_targets a ON a.TARGET_ID = r.REF_ID
      AND (NOT r.HAS_LEVEL OR COALESCE(r.REF_LEVEL = a.TARGET_LEVEL::VARCHAR,FALSE))
      AND (NOT r.HAS_MODULE OR COALESCE(r.REF_MODULE = '67',FALSE))
),
policy_authority_owners AS (
    SELECT p.*, p.L1_ID AS AUTHORITY_OWNER_ID, 3 AS AUTHORITY_OWNER_LEVEL,
           'AUTHORITATIVE_SOURCE_REFERENCES' AS AUTHORITY_FIELD
    FROM policy_paths p WHERE p.L1_ID IS NOT NULL
    UNION ALL
    SELECT p.*, p.L3_ID, 5, 'AUTHORITATIVE_SOURCES'
    FROM policy_paths p WHERE p.L3_ID IS NOT NULL
),
policy_authority_docs AS (
    SELECT DISTINCT p.SOURCE_RECORD_ID AS OWNER_ID,
           IFF(p.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_1_RAW',3,5) AS OWNER_LEVEL,
           TRY_PARSE_JSON(p.METADATA_JSON:value::VARCHAR) AS DOC,
           p.METADATA_JSON:value::VARCHAR IS NOT NULL
             AND TRIM(p.METADATA_JSON:value::VARCHAR) NOT IN ('','null') AS HAS_VALUE
    FROM cat p
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f ON f.FK_TARGET_ELEMENT_HASH = p.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH
      AND f.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN policy_groups g ON g.GROUP_KEY = f.FK_SOURCE_ELEMENT_HASH AND g.POLICY_ID = p.SOURCE_RECORD_ID
      AND g.POLICY_LEVEL = IFF(p.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_1_RAW',3,5)
    WHERE p.ELEMENT_TYPE = 'props' AND p.METADATA_JSON:ns::VARCHAR = 'urn:archer:source:v1'
      AND ((p.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_1_RAW'
            AND p.METADATA_JSON:name::VARCHAR = 'authoritative-source-references')
        OR (p.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW'
            AND p.METADATA_JSON:name::VARCHAR = 'authoritative-sources'))
),
policy_authority_refs AS (
    SELECT DISTINCT d.OWNER_ID,d.OWNER_LEVEL,
           COALESCE(r.value:ContentId::VARCHAR,
                    IFF(TYPEOF(r.value) IN ('INTEGER','DECIMAL','VARCHAR'),r.value::VARCHAR,NULL)) AS REF_ID,
           r.value:LevelId::VARCHAR AS REF_LEVEL,r.value:ModuleId::VARCHAR AS REF_MODULE,
           COALESCE(ARRAY_CONTAINS('LevelId'::VARIANT,OBJECT_KEYS(AS_OBJECT(r.value))),FALSE) AS HAS_LEVEL,
           COALESCE(ARRAY_CONTAINS('ModuleId'::VARIANT,OBJECT_KEYS(AS_OBJECT(r.value))),FALSE) AS HAS_MODULE
    FROM policy_authority_docs d,
         LATERAL FLATTEN(INPUT => CASE WHEN TYPEOF(d.DOC) = 'ARRAY' THEN d.DOC
             WHEN d.DOC IS NULL OR COALESCE(IS_NULL_VALUE(d.DOC),FALSE) THEN ARRAY_CONSTRUCT()
             ELSE ARRAY_CONSTRUCT(d.DOC) END,OUTER => TRUE) r
    WHERE NOT (r.value IS NULL OR COALESCE(IS_NULL_VALUE(r.value),FALSE))
       OR (d.DOC IS NULL AND d.HAS_VALUE)
),
policy_authority_paths AS (
    SELECT p.*,r.REF_ID AS AUTH_REF_ID,r.REF_LEVEL AS AUTH_REF_LEVEL,r.REF_MODULE AS AUTH_REF_MODULE,
           a.*,COALESCE(pn.NAME_VARIANTS,0) AS AUTHORITY_OWNER_NAME_VARIANTS,
           COUNT(a.TARGET_ID) OVER (PARTITION BY p.IR_KEY,p.CONTROL_STANDARD_CONTENT_ID,
             p.CONTROL_STANDARD_NAME,p.L1_ID,p.L2_ID,p.L3_ID,p.AUTHORITY_OWNER_ID,p.AUTHORITY_OWNER_LEVEL,
             r.REF_ID,r.REF_LEVEL,r.REF_MODULE) AS SAVED_PATH_COUNT,
           COALESCE(REGEXP_LIKE(r.REF_ID,'[1-9][0-9]*'),FALSE)
             AND (NOT r.HAS_LEVEL OR COALESCE(r.REF_LEVEL IN ('6','7','8','9'),FALSE))
             AND (NOT r.HAS_MODULE OR COALESCE(r.REF_MODULE = '67',FALSE)) AS VALID_AUTH_REF
    FROM policy_authority_owners p
    JOIN policy_authority_refs r ON r.OWNER_ID = p.AUTHORITY_OWNER_ID AND r.OWNER_LEVEL = p.AUTHORITY_OWNER_LEVEL
    LEFT JOIN policy_name_counts pn ON pn.POLICY_ID = p.AUTHORITY_OWNER_ID AND pn.POLICY_LEVEL = p.AUTHORITY_OWNER_LEVEL
    LEFT JOIN authority_targets a ON a.TARGET_ID = r.REF_ID
      AND (NOT r.HAS_LEVEL OR COALESCE(r.REF_LEVEL = a.TARGET_LEVEL::VARCHAR,FALSE))
      AND (NOT r.HAS_MODULE OR COALESCE(r.REF_MODULE = '67',FALSE))
),
trace AS (
    SELECT ATO_CONTENT_ID, ALLOCATED_CONTROL_CONTENT_ID, SSP_CONTROL_ID,
           CONTROL_STANDARD_CONTENT_ID, CONTROL_STANDARD_NAME, 'POLICY' AS BRANCH,
           L1_ID AS POLICY_LEVEL_1_CONTENT_ID, L1_NAME AS POLICY_LEVEL_1_NAME,
           L2_ID AS POLICY_LEVEL_2_CONTENT_ID, L2_NAME AS POLICY_LEVEL_2_NAME,
           L3_ID AS POLICY_LEVEL_3_CONTENT_ID, L3_NAME AS POLICY_LEVEL_3_NAME,
           NULL::VARCHAR AS AUTHORITATIVE_SOURCE_CONTENT_ID,NULL::VARCHAR AS AUTHORITATIVE_SOURCE_NAME,
           NULL::VARCHAR AS TOPIC_CONTENT_ID,NULL::VARCHAR AS TOPIC_NAME,
           NULL::VARCHAR AS SECTION_CONTENT_ID,NULL::VARCHAR AS SECTION_NAME,
           NULL::VARCHAR AS SUBSECTION_CONTENT_ID,NULL::VARCHAR AS SUBSECTION_NAME,
           CASE WHEN IR_KEY IS NULL THEN 'SSP_IMPLEMENTED_REQUIREMENT_NOT_FOUND'
                WHEN PATH_COUNT = 0 THEN 'IR_NOT_ON_SAVED_SSP_CONTAINMENT_PATH'
                WHEN PATH_COUNT > 1 THEN 'AMBIGUOUS_SAVED_SSP_CONTAINMENT_PATH'
                WHEN ALLOCATION_PROP_COUNT <> 1 OR ALLOCATED_CONTROL_CONTENT_ID IS NULL THEN 'ALLOCATION_ID_MISSING_OR_AMBIGUOUS'
                WHEN DPF_PROP_COUNT <> 1 THEN 'DPF_PROPERTY_MISSING_OR_DUPLICATE'
                WHEN CONTROL_STANDARD_CONTENT_ID IS NULL THEN 'DPF_TARGET_MISSING_OR_INVALID'
                WHEN STANDARD_PLACEMENTS = 0 THEN 'CONTROL_STANDARD_NOT_SAVED_OR_IDENTITY_AMBIGUOUS'
                WHEN STANDARD_NAME_VARIANTS > 1 THEN 'AMBIGUOUS_CONTROL_STANDARD_NAME'
                WHEN NOT COALESCE(REF_EXISTS,FALSE) THEN 'NO_SAVED_POLICY_REFERENCE'
                WHEN NOT VALID_POLICY_REF THEN 'INVALID_SAVED_POLICY_REFERENCE'
                WHEN RESOLVED_POLICY_ID IS NULL THEN 'POLICY_TARGET_NOT_SAVED_OR_LEVEL_CONFLICT'
                WHEN POLICY_NAME_VARIANTS > 1 OR ANCESTOR_NAME_VARIANTS > 1 THEN 'AMBIGUOUS_SAVED_POLICY_NAME'
                WHEN L2_PARENT_COUNT > 1 OR L1_PARENT_COUNT > 1 THEN 'MULTIPLE_POLICY_PARENT_PATHS'
                WHEN INVALID_PARENT_COUNT > 0 THEN 'INVALID_POLICY_PARENT_REFERENCE'
                WHEN MISSING_PARENT_COUNT > 0 THEN 'POLICY_PARENT_NOT_SAVED'
                ELSE 'MATCHED' END AS RELATIONSHIP_STATUS,
           CONCAT('Saved SSP CONTAINS path; Standard placements=',STANDARD_PLACEMENTS,
               '; distinct DPF targets=',DPF_TARGET_COUNT,'; invalid DPF members=',INVALID_DPF_COUNT,
               '; policy target=',COALESCE(POLICY_REF_ID,'not represented'),
               '. Optional missing L1/L2 ancestors are not invented or required. ',
               'Direct L1/L3 Policy-authoritative links are shown separately; preserved memberships are not original-array reconstruction.') AS EVIDENCE_NOTE
    FROM policy_paths
    UNION ALL
    SELECT ATO_CONTENT_ID,ALLOCATED_CONTROL_CONTENT_ID,SSP_CONTROL_ID,
           CONTROL_STANDARD_CONTENT_ID,CONTROL_STANDARD_NAME,'AUTHORITATIVE',
           NULL,NULL,NULL,NULL,NULL,NULL,
           SOURCE_ID,SOURCE_NAME,TOPIC_ID,TOPIC_NAME,SECTION_ID,SECTION_NAME,SUBSECTION_ID,SUBSECTION_NAME,
           CASE WHEN IR_KEY IS NULL THEN 'SSP_IMPLEMENTED_REQUIREMENT_NOT_FOUND'
                WHEN PATH_COUNT = 0 THEN 'IR_NOT_ON_SAVED_SSP_CONTAINMENT_PATH'
                WHEN PATH_COUNT > 1 THEN 'AMBIGUOUS_SAVED_SSP_CONTAINMENT_PATH'
                WHEN ALLOCATION_PROP_COUNT <> 1 OR ALLOCATED_CONTROL_CONTENT_ID IS NULL THEN 'ALLOCATION_ID_MISSING_OR_AMBIGUOUS'
                WHEN DPF_PROP_COUNT <> 1 THEN 'DPF_PROPERTY_MISSING_OR_DUPLICATE'
                WHEN CONTROL_STANDARD_CONTENT_ID IS NULL THEN 'DPF_TARGET_MISSING_OR_INVALID'
                WHEN STANDARD_PLACEMENTS = 0 THEN 'CONTROL_STANDARD_NOT_SAVED_OR_IDENTITY_AMBIGUOUS'
                WHEN STANDARD_NAME_VARIANTS > 1 THEN 'AMBIGUOUS_CONTROL_STANDARD_NAME'
                WHEN NOT COALESCE(REF_EXISTS,FALSE) THEN 'NO_SAVED_AUTHORITATIVE_REFERENCE'
                WHEN NOT VALID_AUTH_REF THEN 'INVALID_SAVED_AUTHORITATIVE_REFERENCE'
                WHEN TARGET_ID IS NULL THEN 'AUTHORITATIVE_TARGET_NOT_IN_SAVED_HIERARCHY'
                WHEN SAVED_PATH_COUNT > 1 THEN 'AMBIGUOUS_SAVED_AUTHORITATIVE_PATH'
                ELSE 'MATCHED' END,
           CONCAT('Saved SSP CONTAINS path; Standard placements=',STANDARD_PLACEMENTS,
               '; distinct DPF targets=',DPF_TARGET_COUNT,'; invalid DPF members=',INVALID_DPF_COUNT,
               '; authoritative target=',COALESCE(AUTH_REF_ID,'not represented'),
               '. AUTHORITATIVE_SOURCES is a typed-resolved saved property and may omit unresolved RAW members. ',
               'Ancestors above the target are actual same-Catalog CONTAINS paths, not reconstructed original parent arrays.')
    FROM authority_paths
    UNION ALL
    SELECT ATO_CONTENT_ID,ALLOCATED_CONTROL_CONTENT_ID,SSP_CONTROL_ID,
           CONTROL_STANDARD_CONTENT_ID,CONTROL_STANDARD_NAME,'POLICY_TO_AUTHORITATIVE_SOURCE',
           L1_ID,L1_NAME,L2_ID,L2_NAME,L3_ID,L3_NAME,
           SOURCE_ID,SOURCE_NAME,TOPIC_ID,TOPIC_NAME,SECTION_ID,SECTION_NAME,SUBSECTION_ID,SUBSECTION_NAME,
           CASE WHEN IR_KEY IS NULL THEN 'SSP_IMPLEMENTED_REQUIREMENT_NOT_FOUND'
                WHEN PATH_COUNT = 0 THEN 'IR_NOT_ON_SAVED_SSP_CONTAINMENT_PATH'
                WHEN PATH_COUNT > 1 THEN 'AMBIGUOUS_SAVED_SSP_CONTAINMENT_PATH'
                WHEN ALLOCATION_PROP_COUNT <> 1 OR ALLOCATED_CONTROL_CONTENT_ID IS NULL THEN 'ALLOCATION_ID_MISSING_OR_AMBIGUOUS'
                WHEN DPF_PROP_COUNT <> 1 THEN 'DPF_PROPERTY_MISSING_OR_DUPLICATE'
                WHEN CONTROL_STANDARD_CONTENT_ID IS NULL THEN 'DPF_TARGET_MISSING_OR_INVALID'
                WHEN STANDARD_PLACEMENTS = 0 THEN 'CONTROL_STANDARD_NOT_SAVED_OR_IDENTITY_AMBIGUOUS'
                WHEN STANDARD_NAME_VARIANTS > 1 THEN 'AMBIGUOUS_CONTROL_STANDARD_NAME'
                WHEN NOT VALID_POLICY_REF OR RESOLVED_POLICY_ID IS NULL THEN 'POLICY_CONTEXT_NOT_RESOLVED'
                WHEN L2_PARENT_COUNT > 1 OR L1_PARENT_COUNT > 1 THEN 'MULTIPLE_POLICY_PARENT_PATHS'
                WHEN INVALID_PARENT_COUNT > 0 OR MISSING_PARENT_COUNT > 0 THEN 'POLICY_PARENT_CONTEXT_UNVERIFIED'
                WHEN AUTHORITY_OWNER_NAME_VARIANTS = 0 THEN 'DIRECT_POLICY_OWNER_NOT_SAVED'
                WHEN AUTHORITY_OWNER_NAME_VARIANTS > 1 OR POLICY_NAME_VARIANTS > 1 OR ANCESTOR_NAME_VARIANTS > 1
                     THEN 'AMBIGUOUS_SAVED_POLICY_NAME'
                WHEN NOT VALID_AUTH_REF THEN 'INVALID_SAVED_POLICY_AUTHORITATIVE_REFERENCE'
                WHEN TARGET_ID IS NULL THEN 'AUTHORITATIVE_TARGET_NOT_IN_SAVED_HIERARCHY'
                WHEN SAVED_PATH_COUNT > 1 THEN 'AMBIGUOUS_SAVED_AUTHORITATIVE_PATH'
                ELSE 'MATCHED_POLICY_TO_AUTHORITATIVE_REFERENCE' END,
           CONCAT('Preserved Policy field ',AUTHORITY_FIELD,'; owner=',AUTHORITY_OWNER_ID,
                  '; authoritative target=',COALESCE(AUTH_REF_ID,'invalid provided member'),
                  '. Only provided L1/L3 reference members create this branch; no L2 relationship is invented. ',
                  'Publication ancestors are actual same-Catalog CONTAINS paths; membership arrays/field origins are not reconstructed.')
    FROM policy_authority_paths

)
SELECT DISTINCT ATO_CONTENT_ID, ALLOCATED_CONTROL_CONTENT_ID, SSP_CONTROL_ID,
       CONTROL_STANDARD_CONTENT_ID, CONTROL_STANDARD_NAME, BRANCH,
       POLICY_LEVEL_1_CONTENT_ID, POLICY_LEVEL_1_NAME,
       POLICY_LEVEL_2_CONTENT_ID, POLICY_LEVEL_2_NAME,
       POLICY_LEVEL_3_CONTENT_ID, POLICY_LEVEL_3_NAME,
       AUTHORITATIVE_SOURCE_CONTENT_ID, AUTHORITATIVE_SOURCE_NAME,
       TOPIC_CONTENT_ID, TOPIC_NAME, SECTION_CONTENT_ID, SECTION_NAME,
       SUBSECTION_CONTENT_ID, SUBSECTION_NAME, RELATIONSHIP_STATUS, EVIDENCE_NOTE
FROM trace
ORDER BY ATO_CONTENT_ID,ALLOCATED_CONTROL_CONTENT_ID,CONTROL_STANDARD_CONTENT_ID,BRANCH,
         POLICY_LEVEL_3_CONTENT_ID,POLICY_LEVEL_2_CONTENT_ID,POLICY_LEVEL_1_CONTENT_ID,
         AUTHORITATIVE_SOURCE_CONTENT_ID,TOPIC_CONTENT_ID,SECTION_CONTENT_ID,SUBSECTION_CONTENT_ID
LIMIT 500;
