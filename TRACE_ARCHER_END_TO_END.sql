-- One read-only joined Archer trace for the same package scope as the saved trace.
-- ONLY the scope selector reads a saved OSCAL table. Relationship values below
-- come from the ten Archer RAW business tables and Archer metadata tables.
-- CURATED_JSON is the mapper's normalized/enriched source input.
-- Identical stored JSON versions collapse; differing/invalid versions remain
-- unverified. No latest version, label-based join, prefix expansion, or URI is guessed.
-- POLICY and AUTHORITATIVE branches remain separate: no unrelated Policy x publication product.
-- A third branch follows only recorded Policy L1/L3 publication references.
-- No Policy Level 2 publication field is invented.
-- Policy ancestors are optional; publication reverse parents use member [0],
-- with the exact bounded two-key parent projection used by the current reader.
-- Other parent objects are not promoted to owners. Multiple array members are noted.
-- The final LIMIT 500 is a row sample, not a complete coverage assertion.

WITH parameters AS (
    SELECT MIN(SOURCE_RECORD_ID)::VARCHAR AS ATO_CONTENT_ID
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT
    WHERE SOURCE_SYSTEM_NAME = 'ARCHER'
      AND SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
      AND ELEMENT_TYPE = 'implemented-requirements'
), raw_rows AS (
    SELECT 'ATO' AS KIND, r.CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           353 AS EXPECTED_LEVEL_ID,
           547 AS EXPECTED_MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW r
    UNION ALL
    SELECT 'ALLOCATION' AS KIND, r.CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           355 AS EXPECTED_LEVEL_ID,
           549 AS EXPECTED_MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_ALLOCATED_CONTROLS_CONTROL_RAW r
    UNION ALL
    SELECT 'STANDARD' AS KIND, r.CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           41 AS EXPECTED_LEVEL_ID,
           66 AS EXPECTED_MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_STANDARDS_RAW r
    UNION ALL
    SELECT 'POLICY_L1' AS KIND, r.CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           3 AS EXPECTED_LEVEL_ID,
           65 AS EXPECTED_MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_POLICIES_POLICY_LEVEL_1_RAW r
    UNION ALL
    SELECT 'POLICY_L2' AS KIND, r.CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           4 AS EXPECTED_LEVEL_ID,
           65 AS EXPECTED_MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW r
    UNION ALL
    SELECT 'POLICY_L3' AS KIND, r.CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           5 AS EXPECTED_LEVEL_ID,
           65 AS EXPECTED_MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW r
    UNION ALL
    SELECT 'SOURCE' AS KIND, r.CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           6 AS EXPECTED_LEVEL_ID,
           67 AS EXPECTED_MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW r
    UNION ALL
    SELECT 'TOPIC' AS KIND, r.CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           7 AS EXPECTED_LEVEL_ID,
           67 AS EXPECTED_MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW r
    UNION ALL
    SELECT 'SECTION' AS KIND, r.CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           8 AS EXPECTED_LEVEL_ID,
           67 AS EXPECTED_MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW r
    UNION ALL
    SELECT 'SUBSECTION' AS KIND, r.CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           9 AS EXPECTED_LEVEL_ID,
           67 AS EXPECTED_MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW r
), raw_rollup AS (
    SELECT KIND, CONTENT_ID, MIN(EXPECTED_LEVEL_ID) AS EXPECTED_LEVEL_ID,
           MIN(EXPECTED_MODULE_ID) AS EXPECTED_MODULE_ID,
           COUNT(*) AS STORED_ROWS,
           COUNT(DISTINCT TO_JSON(DOC)) AS DISTINCT_JSON_VERSIONS,
           COUNT_IF(NOT COALESCE(IS_OBJECT(DOC), FALSE) OR TO_JSON(DOC) = '{}') AS INVALID_DOCUMENTS,
           MIN(TO_JSON(DOC)) AS ONLY_JSON_TEXT
    FROM raw_rows
    GROUP BY KIND, CONTENT_ID
), content_metadata AS (
    SELECT CONTENT_ID::VARCHAR AS CONTENT_ID, COUNT(*) AS METADATA_ROWS,
           MIN(LEVEL_ID) AS LEVEL_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_META_CONTENT
    GROUP BY CONTENT_ID::VARCHAR
), level_metadata AS (
    SELECT LEVEL_ID, COUNT(*) AS LEVEL_ROWS, MIN(MODULE_ID) AS MODULE_ID
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_META_LEVEL
    GROUP BY LEVEL_ID
), nodes AS (
    SELECT r.*, m.METADATA_ROWS, m.LEVEL_ID, l.LEVEL_ROWS, l.MODULE_ID,
           IFF(r.DISTINCT_JSON_VERSIONS = 1 AND r.INVALID_DOCUMENTS = 0,
               TRY_PARSE_JSON(r.ONLY_JSON_TEXT, 's'), NULL) AS DOC,
           CASE WHEN NOT COALESCE(REGEXP_LIKE(r.CONTENT_ID, '[1-9][0-9]*'), FALSE)
                     THEN 'SOURCE_CONTENT_ID_INVALID'
                WHEN r.INVALID_DOCUMENTS > 0 THEN 'SOURCE_JSON_INVALID_OR_EMPTY'
                WHEN r.DISTINCT_JSON_VERSIONS <> 1 THEN 'DIFFERING_STORED_SOURCE_VERSIONS'
                WHEN m.METADATA_ROWS IS DISTINCT FROM 1 THEN 'SOURCE_CONTENT_METADATA_MISSING_OR_AMBIGUOUS'
                WHEN l.LEVEL_ROWS IS DISTINCT FROM 1 OR l.MODULE_ID IS NULL OR l.MODULE_ID <= 0
                     THEN 'SOURCE_LEVEL_METADATA_MISSING_OR_AMBIGUOUS'
                WHEN r.EXPECTED_LEVEL_ID IS NOT NULL AND m.LEVEL_ID IS DISTINCT FROM r.EXPECTED_LEVEL_ID
                     THEN 'SOURCE_LEVEL_CONFLICT'
                WHEN r.EXPECTED_MODULE_ID IS NOT NULL AND l.MODULE_ID IS DISTINCT FROM r.EXPECTED_MODULE_ID
                     THEN 'SOURCE_MODULE_CONFLICT'
                ELSE 'READY' END AS NODE_STATUS
    FROM raw_rollup r
    LEFT JOIN content_metadata m ON m.CONTENT_ID = r.CONTENT_ID
    LEFT JOIN level_metadata l ON l.LEVEL_ID = m.LEVEL_ID
), field_specs (OWNER_KIND, FIELD_NAME, FIRST_PARENT_ONLY) AS (
    SELECT * FROM VALUES
      ('ALLOCATION', 'AUTHORIZATION_PACKAGE', TRUE),
      ('ALLOCATION', 'DIGITAL_POLICY_FRAMEWORK_DPF_REFERENCE', FALSE),
      ('STANDARD', 'POLICY_HIERARCHY_LEVEL_1_2_3', FALSE),
      ('STANDARD', 'AUTHORITATIVE_SOURCES', FALSE),
      ('POLICY_L3', 'POLICY_LEVEL_2_REFERENCE', FALSE),
      ('POLICY_L2', 'POLICY_LEVEL_1_REFERENCE', FALSE),
      ('POLICY_L1', 'AUTHORITATIVE_SOURCE_REFERENCES', FALSE),
      ('POLICY_L3', 'AUTHORITATIVE_SOURCES', FALSE),
      ('TOPIC', 'SOURCE_REFERENCES', TRUE),
      ('SECTION', 'TOPIC_REFERENCES', TRUE),
      ('SUBSECTION', 'SECTION_REFERENCES', TRUE)
), source_fields AS (
    SELECT n.KIND AS OWNER_KIND, n.CONTENT_ID AS OWNER_CONTENT_ID,
           f.FIELD_NAME, f.FIRST_PARENT_ONLY, GET(n.DOC, f.FIELD_NAME) AS FIELD_VALUE
    FROM nodes n JOIN field_specs f ON f.OWNER_KIND = n.KIND
), reference_members AS (
    SELECT s.*, IFF(IS_ARRAY(s.FIELD_VALUE), ARRAY_SIZE(AS_ARRAY(s.FIELD_VALUE)), NULL) AS SOURCE_MEMBER_COUNT,
           r.INDEX AS REFERENCE_INDEX, r.VALUE AS MEMBER
    FROM source_fields s,
         LATERAL FLATTEN(INPUT => CASE
           WHEN s.FIRST_PARENT_ONLY THEN ARRAY_CONSTRUCT(GET(AS_ARRAY(s.FIELD_VALUE), 0))
           WHEN IS_ARRAY(s.FIELD_VALUE) THEN AS_ARRAY(s.FIELD_VALUE)
           WHEN s.FIELD_VALUE IS NULL OR COALESCE(IS_NULL_VALUE(s.FIELD_VALUE), FALSE) THEN ARRAY_CONSTRUCT()
           ELSE ARRAY_CONSTRUCT(s.FIELD_VALUE) END, OUTER => TRUE) r
), reference_shapes AS (
    SELECT r.*, COALESCE(
               ARRAY_SIZE(OBJECT_KEYS(AS_OBJECT(MEMBER))) = 2
               AND TYPEOF(GET(AS_OBJECT(MEMBER),'ContentId')) IN ('INTEGER','DECIMAL')
               AND REGEXP_LIKE(GET(AS_OBJECT(MEMBER),'ContentId')::VARCHAR,'[1-9][0-9]*')
               AND REGEXP_LIKE(GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR,'[A-Z][A-Z0-9_]{0,127}')
               AND GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR NOT IN ('CONTENTID','LEVELID','CONTENT_ID','LEVEL_ID')
               AND NOT STARTSWITH(GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR,'OSCAL_')
               AND TYPEOF(GET(AS_OBJECT(MEMBER),GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR))
                   IN ('VARCHAR','INTEGER','DECIMAL','DOUBLE','BOOLEAN','DATE','TIMESTAMP_NTZ')
               AND OCTET_LENGTH(GET(AS_OBJECT(MEMBER),GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR)::VARCHAR) <= 512
               AND REGEXP_LIKE(GET(AS_OBJECT(MEMBER),GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR)::VARCHAR,'.*[^[:space:]].*','s'), FALSE) AS BOUNDED_PARENT_PROJECTION
    FROM reference_members r
), reference_values AS (
    SELECT r.*,
           IFF(FIRST_PARENT_ONLY,
               IFF(BOUNDED_PARENT_PROJECTION,GET(AS_OBJECT(MEMBER),'ContentId'),MEMBER),
               IFF(IS_OBJECT(MEMBER),GET(AS_OBJECT(MEMBER),'ContentId'),MEMBER)) AS ID_VALUE,
           GET(AS_OBJECT(MEMBER), 'LevelId') AS DECLARED_LEVEL_VALUE,
           GET(AS_OBJECT(MEMBER), 'ModuleId') AS DECLARED_MODULE_VALUE,
           COALESCE(ARRAY_CONTAINS('LevelId'::VARIANT, OBJECT_KEYS(AS_OBJECT(MEMBER))), FALSE) AS HAS_DECLARED_LEVEL,
           COALESCE(ARRAY_CONTAINS('ModuleId'::VARIANT, OBJECT_KEYS(AS_OBJECT(MEMBER))), FALSE) AS HAS_DECLARED_MODULE
    FROM reference_shapes r
), reference_ids AS (
    SELECT r.*,
           IFF(TYPEOF(ID_VALUE) IN ('INTEGER','DECIMAL','VARCHAR')
               AND REGEXP_LIKE(ID_VALUE::VARCHAR, '[1-9][0-9]*'), ID_VALUE::VARCHAR, NULL) AS TARGET_CONTENT_ID,
           IFF(TYPEOF(DECLARED_LEVEL_VALUE) IN ('INTEGER','DECIMAL','VARCHAR')
               AND REGEXP_LIKE(DECLARED_LEVEL_VALUE::VARCHAR, '[1-9][0-9]*'),
               TRY_TO_NUMBER(DECLARED_LEVEL_VALUE::VARCHAR), NULL) AS DECLARED_LEVEL_ID,
           IFF(TYPEOF(DECLARED_MODULE_VALUE) IN ('INTEGER','DECIMAL','VARCHAR')
               AND REGEXP_LIKE(DECLARED_MODULE_VALUE::VARCHAR, '[1-9][0-9]*'),
               TRY_TO_NUMBER(DECLARED_MODULE_VALUE::VARCHAR), NULL) AS DECLARED_MODULE_ID
    FROM reference_values r
), references_checked AS (
    SELECT r.*, m.LEVEL_ID AS TARGET_LEVEL_ID, l.MODULE_ID AS TARGET_MODULE_ID,
           CASE m.LEVEL_ID WHEN 3 THEN 'POLICY_L1' WHEN 4 THEN 'POLICY_L2' WHEN 5 THEN 'POLICY_L3'
                WHEN 6 THEN 'SOURCE' WHEN 7 THEN 'TOPIC' WHEN 8 THEN 'SECTION' WHEN 9 THEN 'SUBSECTION'
                WHEN 41 THEN 'STANDARD' END AS TARGET_KIND,
           CASE WHEN MEMBER IS NULL OR COALESCE(IS_NULL_VALUE(MEMBER), FALSE) THEN 'NO_REFERENCE_RECORDED'
                WHEN TARGET_CONTENT_ID IS NULL THEN 'REFERENCE_CONTENT_ID_INVALID'
                WHEN HAS_DECLARED_LEVEL AND DECLARED_LEVEL_ID IS NULL THEN 'DECLARED_LEVEL_INVALID'
                WHEN HAS_DECLARED_MODULE AND DECLARED_MODULE_ID IS NULL THEN 'DECLARED_MODULE_INVALID'
                WHEN m.METADATA_ROWS IS DISTINCT FROM 1 THEN 'TARGET_CONTENT_METADATA_MISSING_OR_AMBIGUOUS'
                WHEN l.LEVEL_ROWS IS DISTINCT FROM 1 OR l.MODULE_ID IS NULL OR l.MODULE_ID <= 0
                     THEN 'TARGET_LEVEL_METADATA_MISSING_OR_AMBIGUOUS'
                WHEN HAS_DECLARED_LEVEL AND DECLARED_LEVEL_ID IS DISTINCT FROM m.LEVEL_ID THEN 'DECLARED_LEVEL_CONFLICT'
                WHEN HAS_DECLARED_MODULE AND DECLARED_MODULE_ID IS DISTINCT FROM l.MODULE_ID THEN 'DECLARED_MODULE_CONFLICT'
                WHEN FIELD_NAME = 'AUTHORIZATION_PACKAGE'
                     AND (m.LEVEL_ID <> 353 OR l.MODULE_ID <> 547) THEN 'REFERENCE_TARGET_DOMAIN_CONFLICT'
                WHEN FIELD_NAME = 'DIGITAL_POLICY_FRAMEWORK_DPF_REFERENCE'
                     AND (m.LEVEL_ID <> 41 OR l.MODULE_ID <> 66) THEN 'REFERENCE_TARGET_DOMAIN_CONFLICT'
                WHEN FIELD_NAME = 'POLICY_HIERARCHY_LEVEL_1_2_3'
                     AND (m.LEVEL_ID NOT IN (3,4,5) OR l.MODULE_ID <> 65) THEN 'REFERENCE_TARGET_DOMAIN_CONFLICT'
                WHEN FIELD_NAME = 'POLICY_LEVEL_2_REFERENCE'
                     AND (m.LEVEL_ID <> 4 OR l.MODULE_ID <> 65) THEN 'REFERENCE_TARGET_DOMAIN_CONFLICT'
                WHEN FIELD_NAME = 'POLICY_LEVEL_1_REFERENCE'
                     AND (m.LEVEL_ID <> 3 OR l.MODULE_ID <> 65) THEN 'REFERENCE_TARGET_DOMAIN_CONFLICT'
                WHEN FIELD_NAME IN ('AUTHORITATIVE_SOURCES','AUTHORITATIVE_SOURCE_REFERENCES')
                     AND (m.LEVEL_ID NOT IN (6,7,8,9) OR l.MODULE_ID <> 67) THEN 'REFERENCE_TARGET_DOMAIN_CONFLICT'
                WHEN FIELD_NAME = 'SOURCE_REFERENCES'
                     AND (m.LEVEL_ID <> 6 OR l.MODULE_ID <> 67) THEN 'REFERENCE_TARGET_DOMAIN_CONFLICT'
                WHEN FIELD_NAME = 'TOPIC_REFERENCES'
                     AND (m.LEVEL_ID <> 7 OR l.MODULE_ID <> 67) THEN 'REFERENCE_TARGET_DOMAIN_CONFLICT'
                WHEN FIELD_NAME = 'SECTION_REFERENCES'
                     AND (m.LEVEL_ID <> 8 OR l.MODULE_ID <> 67) THEN 'REFERENCE_TARGET_DOMAIN_CONFLICT'
                ELSE 'REFERENCE_READY' END AS REFERENCE_STATUS
    FROM reference_ids r
    LEFT JOIN content_metadata m ON m.CONTENT_ID = r.TARGET_CONTENT_ID
    LEFT JOIN level_metadata l ON l.LEVEL_ID = m.LEVEL_ID
), reference_cardinality AS (
    SELECT OWNER_KIND, OWNER_CONTENT_ID, FIELD_NAME,
           COUNT(DISTINCT IFF(REFERENCE_STATUS='REFERENCE_READY',TARGET_CONTENT_ID,NULL)) AS READY_TARGET_COUNT
    FROM references_checked GROUP BY OWNER_KIND, OWNER_CONTENT_ID, FIELD_NAME
), allocation_ownership_members AS (
    SELECT r.CONTENT_ID, GET(AS_ARRAY(r.DOC:AUTHORIZATION_PACKAGE),0) AS MEMBER
    FROM raw_rows r WHERE r.KIND = 'ALLOCATION'
), allocation_candidates AS (
    -- Keep an ambiguous Allocation in scope if ANY stored version records this
    -- package in member [0]. Only the exact current bounded parent projection
    -- is recovered; other objects retain their JSON spelling and cannot match.
    SELECT DISTINCT r.CONTENT_ID
    FROM allocation_ownership_members r CROSS JOIN parameters p
    WHERE IFF(COALESCE(
               ARRAY_SIZE(OBJECT_KEYS(AS_OBJECT(MEMBER))) = 2
               AND TYPEOF(GET(AS_OBJECT(MEMBER),'ContentId')) IN ('INTEGER','DECIMAL')
               AND REGEXP_LIKE(GET(AS_OBJECT(MEMBER),'ContentId')::VARCHAR,'[1-9][0-9]*')
               AND REGEXP_LIKE(GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR,'[A-Z][A-Z0-9_]{0,127}')
               AND GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR NOT IN ('CONTENTID','LEVELID','CONTENT_ID','LEVEL_ID')
               AND NOT STARTSWITH(GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR,'OSCAL_')
               AND TYPEOF(GET(AS_OBJECT(MEMBER),GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR))
                   IN ('VARCHAR','INTEGER','DECIMAL','DOUBLE','BOOLEAN','DATE','TIMESTAMP_NTZ')
               AND OCTET_LENGTH(GET(AS_OBJECT(MEMBER),GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR)::VARCHAR) <= 512
               AND REGEXP_LIKE(GET(AS_OBJECT(MEMBER),GET(ARRAY_EXCEPT(OBJECT_KEYS(AS_OBJECT(MEMBER)),ARRAY_CONSTRUCT('ContentId')),0)::VARCHAR)::VARCHAR,'.*[^[:space:]].*','s'), FALSE),
              GET(AS_OBJECT(MEMBER),'ContentId'),MEMBER)::VARCHAR = p.ATO_CONTENT_ID
), base_chain AS (
    SELECT p.ATO_CONTENT_ID, a.CONTENT_ID AS ALLOCATED_CONTROL_CONTENT_ID,
           a.DOC:CONTROL_NUMBER::VARCHAR AS SSP_CONTROL_ID,
           d.TARGET_CONTENT_ID AS CONTROL_STANDARD_CONTENT_ID,
           s.DOC:CONTROL_STANDARD_NAME::VARCHAR AS CONTROL_STANDARD_NAME,
           a.STORED_ROWS AS ALLOCATION_STORED_ROWS, a.DISTINCT_JSON_VERSIONS AS ALLOCATION_JSON_VERSIONS,
           s.STORED_ROWS AS STANDARD_STORED_ROWS, s.DISTINCT_JSON_VERSIONS AS STANDARD_JSON_VERSIONS,
           own.SOURCE_MEMBER_COUNT AS ALLOCATION_OWNER_MEMBER_COUNT,
           CASE WHEN p.ATO_CONTENT_ID IS NULL THEN 'NO_SAVED_PACKAGE_SCOPE'
                WHEN pkg.CONTENT_ID IS NULL THEN 'ATO_RAW_ROW_MISSING'
                WHEN pkg.NODE_STATUS <> 'READY' THEN pkg.NODE_STATUS
                WHEN a.CONTENT_ID IS NULL THEN 'NO_RUNTIME_OWNED_ALLOCATION_FOUND'
                WHEN a.NODE_STATUS <> 'READY' THEN a.NODE_STATUS
                WHEN own.REFERENCE_STATUS IS DISTINCT FROM 'REFERENCE_READY'
                  OR own.TARGET_CONTENT_ID IS DISTINCT FROM p.ATO_CONTENT_ID THEN 'ALLOCATION_OWNER_REFERENCE_UNVERIFIED'
                WHEN d.REFERENCE_STATUS IS DISTINCT FROM 'REFERENCE_READY' THEN COALESCE(d.REFERENCE_STATUS,'STANDARD_REFERENCE_MISSING')
                WHEN s.CONTENT_ID IS NULL THEN 'STANDARD_RAW_ROW_MISSING'
                WHEN s.NODE_STATUS <> 'READY' THEN s.NODE_STATUS
                ELSE 'BASE_READY' END AS BASE_STATUS
    FROM parameters p
    LEFT JOIN nodes pkg ON pkg.KIND = 'ATO' AND pkg.CONTENT_ID = p.ATO_CONTENT_ID
    LEFT JOIN allocation_candidates ac ON TRUE
    LEFT JOIN nodes a ON a.KIND = 'ALLOCATION' AND a.CONTENT_ID = ac.CONTENT_ID
    LEFT JOIN references_checked own ON own.OWNER_KIND = 'ALLOCATION' AND own.OWNER_CONTENT_ID = a.CONTENT_ID
      AND own.FIELD_NAME = 'AUTHORIZATION_PACKAGE'
    LEFT JOIN references_checked d ON d.OWNER_KIND = 'ALLOCATION' AND d.OWNER_CONTENT_ID = a.CONTENT_ID
      AND d.FIELD_NAME = 'DIGITAL_POLICY_FRAMEWORK_DPF_REFERENCE'
    LEFT JOIN nodes s ON s.KIND = 'STANDARD' AND s.CONTENT_ID = d.TARGET_CONTENT_ID
), policy_start AS (
    SELECT b.*, r.REFERENCE_INDEX, r.TARGET_CONTENT_ID AS DIRECT_POLICY_ID, r.TARGET_KIND AS DIRECT_POLICY_KIND,
           r.REFERENCE_STATUS AS DIRECT_POLICY_STATUS,
           IFF(r.TARGET_KIND = 'POLICY_L3', r.TARGET_CONTENT_ID, NULL) AS P3_ID,
           IFF(r.TARGET_KIND = 'POLICY_L2', r.TARGET_CONTENT_ID, NULL) AS DIRECT_P2_ID,
           IFF(r.TARGET_KIND = 'POLICY_L1', r.TARGET_CONTENT_ID, NULL) AS DIRECT_P1_ID
    FROM base_chain b
    LEFT JOIN references_checked r ON r.OWNER_KIND = 'STANDARD'
      AND r.OWNER_CONTENT_ID = b.CONTROL_STANDARD_CONTENT_ID AND r.FIELD_NAME = 'POLICY_HIERARCHY_LEVEL_1_2_3'
), policy_l2 AS (
    SELECT s.*, p3.NODE_STATUS AS P3_STATUS, p3.DOC:POLICY_LEVEL_3_NAME::VARCHAR AS P3_NAME,
           r.REFERENCE_STATUS AS P2_REF_STATUS, card.READY_TARGET_COUNT AS P2_PARENT_TARGETS,
           COALESCE(s.DIRECT_P2_ID, IFF(r.REFERENCE_STATUS = 'REFERENCE_READY', r.TARGET_CONTENT_ID, NULL)) AS P2_ID
    FROM policy_start s
    LEFT JOIN nodes p3 ON p3.KIND = 'POLICY_L3' AND p3.CONTENT_ID = s.P3_ID
    LEFT JOIN references_checked r ON r.OWNER_KIND = 'POLICY_L3' AND r.OWNER_CONTENT_ID = s.P3_ID
      AND r.FIELD_NAME = 'POLICY_LEVEL_2_REFERENCE'
    LEFT JOIN reference_cardinality card ON card.OWNER_KIND='POLICY_L3'
      AND card.OWNER_CONTENT_ID=s.P3_ID AND card.FIELD_NAME='POLICY_LEVEL_2_REFERENCE'
), policy_l1 AS (
    SELECT s.*, p2.NODE_STATUS AS P2_STATUS, p2.DOC:POLICY_LEVEL_2_NAME::VARCHAR AS P2_NAME,
           r.REFERENCE_STATUS AS P1_REF_STATUS, card.READY_TARGET_COUNT AS P1_PARENT_TARGETS,
           COALESCE(s.DIRECT_P1_ID, IFF(r.REFERENCE_STATUS = 'REFERENCE_READY', r.TARGET_CONTENT_ID, NULL)) AS P1_ID
    FROM policy_l2 s
    LEFT JOIN nodes p2 ON p2.KIND = 'POLICY_L2' AND p2.CONTENT_ID = s.P2_ID
    LEFT JOIN references_checked r ON r.OWNER_KIND = 'POLICY_L2' AND r.OWNER_CONTENT_ID = s.P2_ID
      AND r.FIELD_NAME = 'POLICY_LEVEL_1_REFERENCE'
    LEFT JOIN reference_cardinality card ON card.OWNER_KIND='POLICY_L2'
      AND card.OWNER_CONTENT_ID=s.P2_ID AND card.FIELD_NAME='POLICY_LEVEL_1_REFERENCE'
), policy_branch AS (
    SELECT s.ATO_CONTENT_ID, s.ALLOCATED_CONTROL_CONTENT_ID, s.SSP_CONTROL_ID,
           s.CONTROL_STANDARD_CONTENT_ID, s.CONTROL_STANDARD_NAME, 'POLICY' AS BRANCH,
           s.P1_ID AS POLICY_LEVEL_1_CONTENT_ID, p1.DOC:POLICY_LEVEL_1_NAME::VARCHAR AS POLICY_LEVEL_1_NAME,
           s.P2_ID AS POLICY_LEVEL_2_CONTENT_ID, s.P2_NAME AS POLICY_LEVEL_2_NAME,
           s.P3_ID AS POLICY_LEVEL_3_CONTENT_ID, s.P3_NAME AS POLICY_LEVEL_3_NAME,
           NULL::VARCHAR AS AUTHORITATIVE_SOURCE_CONTENT_ID, NULL::VARCHAR AS AUTHORITATIVE_SOURCE_NAME,
           NULL::VARCHAR AS TOPIC_CONTENT_ID, NULL::VARCHAR AS TOPIC_NAME,
           NULL::VARCHAR AS SECTION_CONTENT_ID, NULL::VARCHAR AS SECTION_NAME,
           NULL::VARCHAR AS SUBSECTION_CONTENT_ID, NULL::VARCHAR AS SUBSECTION_NAME,
           CASE WHEN s.BASE_STATUS <> 'BASE_READY' THEN s.BASE_STATUS
                WHEN s.DIRECT_POLICY_STATUS IS DISTINCT FROM 'REFERENCE_READY'
                     THEN COALESCE(s.DIRECT_POLICY_STATUS,'POLICY_REFERENCE_MISSING')
                WHEN s.DIRECT_POLICY_KIND NOT IN ('POLICY_L1','POLICY_L2','POLICY_L3') THEN 'POLICY_TARGET_DOMAIN_UNVERIFIED'
                WHEN (s.P3_ID IS NOT NULL AND s.P3_STATUS IS NULL)
                  OR (s.DIRECT_P2_ID IS NOT NULL AND s.P2_STATUS IS NULL)
                  OR (s.DIRECT_P1_ID IS NOT NULL AND p1.NODE_STATUS IS NULL) THEN 'DIRECT_POLICY_RAW_ROW_MISSING'
                WHEN (s.P3_ID IS NOT NULL AND s.P3_STATUS <> 'READY')
                  OR (s.P2_ID IS NOT NULL AND s.P2_STATUS <> 'READY')
                  OR (s.P1_ID IS NOT NULL AND p1.NODE_STATUS <> 'READY') THEN 'POLICY_STORED_SOURCE_UNVERIFIED'
                WHEN COALESCE(s.P2_REF_STATUS,'NO_REFERENCE_RECORDED') NOT IN ('REFERENCE_READY','NO_REFERENCE_RECORDED')
                  OR COALESCE(s.P1_REF_STATUS,'NO_REFERENCE_RECORDED') NOT IN ('REFERENCE_READY','NO_REFERENCE_RECORDED')
                  OR (s.P2_ID IS NOT NULL AND s.P2_STATUS IS NULL)
                  OR (s.P1_ID IS NOT NULL AND p1.NODE_STATUS IS NULL) THEN 'RECORDED_POLICY_PARENT_UNRESOLVED'
                WHEN COALESCE(s.P2_PARENT_TARGETS,0)>1 OR COALESCE(s.P1_PARENT_TARGETS,0)>1
                     THEN 'MULTIPLE_RECORDED_POLICY_PARENT_PATHS'
                ELSE 'MATCHED_POLICY_REFERENCE' END AS RELATIONSHIP_STATUS,
           'RAW field POLICY_HIERARCHY_LEVEL_1_2_3; reference index=' || COALESCE(s.REFERENCE_INDEX::VARCHAR,'none')
           || '; direct target=' || COALESCE(s.DIRECT_POLICY_ID,'none')
           || '; optional ancestors may be absent; all recorded parent-reference members remain separate'
           || '; L3-to-L2/L2-to-L1 distinct recorded parent counts=' || COALESCE(s.P2_PARENT_TARGETS::VARCHAR,'0')
           || '/' || COALESCE(s.P1_PARENT_TARGETS::VARCHAR,'0')
           || '; Allocation AUTHORIZATION_PACKAGE member count=' || COALESCE(s.ALLOCATION_OWNER_MEMBER_COUNT::VARCHAR,'see policy context')
           || '; Allocation stored rows/JSON versions=' || COALESCE(s.ALLOCATION_STORED_ROWS::VARCHAR,'0')
           || '/' || COALESCE(s.ALLOCATION_JSON_VERSIONS::VARCHAR,'0')
           || '; Standard stored rows/JSON versions=' || COALESCE(s.STANDARD_STORED_ROWS::VARCHAR,'0')
           || '/' || COALESCE(s.STANDARD_JSON_VERSIONS::VARCHAR,'0') AS EVIDENCE_NOTE
    FROM policy_l1 s
    LEFT JOIN nodes p1 ON p1.KIND = 'POLICY_L1' AND p1.CONTENT_ID = s.P1_ID
), policy_authority_owners AS (
    SELECT p.*, 'POLICY_L1' AS AUTHORITY_OWNER_KIND, p.POLICY_LEVEL_1_CONTENT_ID AS AUTHORITY_OWNER_ID,
           'AUTHORITATIVE_SOURCE_REFERENCES' AS AUTHORITY_FIELD
    FROM policy_branch p WHERE p.POLICY_LEVEL_1_CONTENT_ID IS NOT NULL
    UNION ALL
    SELECT p.*, 'POLICY_L3', p.POLICY_LEVEL_3_CONTENT_ID, 'AUTHORITATIVE_SOURCES'
    FROM policy_branch p WHERE p.POLICY_LEVEL_3_CONTENT_ID IS NOT NULL
), authority_start AS (
    SELECT b.*, r.REFERENCE_INDEX, r.TARGET_CONTENT_ID AS DIRECT_AUTHORITY_ID,
           r.TARGET_KIND AS DIRECT_AUTHORITY_KIND, r.REFERENCE_STATUS AS DIRECT_AUTHORITY_STATUS,
           IFF(r.TARGET_KIND = 'SUBSECTION',r.TARGET_CONTENT_ID,NULL) AS SS_ID,
           IFF(r.TARGET_KIND = 'SECTION',r.TARGET_CONTENT_ID,NULL) AS DIRECT_SECTION_ID,
           IFF(r.TARGET_KIND = 'TOPIC',r.TARGET_CONTENT_ID,NULL) AS DIRECT_TOPIC_ID,
           IFF(r.TARGET_KIND = 'SOURCE',r.TARGET_CONTENT_ID,NULL) AS DIRECT_SOURCE_ID,
           NULL::VARCHAR AS POLICY_LEVEL_1_CONTENT_ID, NULL::VARCHAR AS POLICY_LEVEL_1_NAME,
           NULL::VARCHAR AS POLICY_LEVEL_2_CONTENT_ID, NULL::VARCHAR AS POLICY_LEVEL_2_NAME,
           NULL::VARCHAR AS POLICY_LEVEL_3_CONTENT_ID, NULL::VARCHAR AS POLICY_LEVEL_3_NAME,
           'AUTHORITATIVE' AS BRANCH, 'AUTHORITATIVE_SOURCES' AS INPUT_FIELD,
           'STANDARD' AS AUTHORITY_OWNER_KIND, b.CONTROL_STANDARD_CONTENT_ID AS AUTHORITY_OWNER_ID,
           NULL::VARCHAR AS POLICY_CONTEXT_NOTE
    FROM base_chain b
    LEFT JOIN references_checked r ON r.OWNER_KIND = 'STANDARD'
      AND r.OWNER_CONTENT_ID = b.CONTROL_STANDARD_CONTENT_ID AND r.FIELD_NAME = 'AUTHORITATIVE_SOURCES'
    UNION ALL
    SELECT p.ATO_CONTENT_ID, p.ALLOCATED_CONTROL_CONTENT_ID, p.SSP_CONTROL_ID,
           p.CONTROL_STANDARD_CONTENT_ID, p.CONTROL_STANDARD_NAME,
           NULL::NUMBER, NULL::NUMBER, NULL::NUMBER, NULL::NUMBER, NULL::NUMBER,
           IFF(p.RELATIONSHIP_STATUS = 'MATCHED_POLICY_REFERENCE','BASE_READY',p.RELATIONSHIP_STATUS),
           r.REFERENCE_INDEX, r.TARGET_CONTENT_ID, r.TARGET_KIND, r.REFERENCE_STATUS,
           IFF(r.TARGET_KIND = 'SUBSECTION',r.TARGET_CONTENT_ID,NULL),
           IFF(r.TARGET_KIND = 'SECTION',r.TARGET_CONTENT_ID,NULL),
           IFF(r.TARGET_KIND = 'TOPIC',r.TARGET_CONTENT_ID,NULL),
           IFF(r.TARGET_KIND = 'SOURCE',r.TARGET_CONTENT_ID,NULL),
           p.POLICY_LEVEL_1_CONTENT_ID, p.POLICY_LEVEL_1_NAME,
           p.POLICY_LEVEL_2_CONTENT_ID, p.POLICY_LEVEL_2_NAME,
           p.POLICY_LEVEL_3_CONTENT_ID, p.POLICY_LEVEL_3_NAME,
           'POLICY_TO_AUTHORITATIVE_SOURCE', p.AUTHORITY_FIELD,
           p.AUTHORITY_OWNER_KIND, p.AUTHORITY_OWNER_ID, p.EVIDENCE_NOTE
    FROM policy_authority_owners p
    JOIN references_checked r ON r.OWNER_KIND = p.AUTHORITY_OWNER_KIND
      AND r.OWNER_CONTENT_ID = p.AUTHORITY_OWNER_ID AND r.FIELD_NAME = p.AUTHORITY_FIELD
    WHERE r.REFERENCE_STATUS <> 'NO_REFERENCE_RECORDED'
), authority_section AS (
    SELECT s.*, ss.NODE_STATUS AS SS_STATUS, ss.DOC:SUB_SECTION_NAME::VARCHAR AS SS_NAME,
           r.REFERENCE_STATUS AS SECTION_REF_STATUS, r.SOURCE_MEMBER_COUNT AS SS_PARENT_MEMBERS,
           COALESCE(s.DIRECT_SECTION_ID,IFF(r.REFERENCE_STATUS='REFERENCE_READY',r.TARGET_CONTENT_ID,NULL)) AS SECTION_ID
    FROM authority_start s
    LEFT JOIN nodes ss ON ss.KIND='SUBSECTION' AND ss.CONTENT_ID=s.SS_ID
    LEFT JOIN references_checked r ON r.OWNER_KIND='SUBSECTION' AND r.OWNER_CONTENT_ID=s.SS_ID
      AND r.FIELD_NAME='SECTION_REFERENCES'
), authority_topic AS (
    SELECT s.*, sec.NODE_STATUS AS SECTION_STATUS, sec.DOC:SECTION_NAME::VARCHAR AS SECTION_NAME,
           r.REFERENCE_STATUS AS TOPIC_REF_STATUS, r.SOURCE_MEMBER_COUNT AS SECTION_PARENT_MEMBERS,
           COALESCE(s.DIRECT_TOPIC_ID,IFF(r.REFERENCE_STATUS='REFERENCE_READY',r.TARGET_CONTENT_ID,NULL)) AS TOPIC_ID
    FROM authority_section s
    LEFT JOIN nodes sec ON sec.KIND='SECTION' AND sec.CONTENT_ID=s.SECTION_ID
    LEFT JOIN references_checked r ON r.OWNER_KIND='SECTION' AND r.OWNER_CONTENT_ID=s.SECTION_ID
      AND r.FIELD_NAME='TOPIC_REFERENCES'
), authority_source AS (
    SELECT s.*, t.NODE_STATUS AS TOPIC_STATUS, t.DOC:TOPIC_NAME::VARCHAR AS TOPIC_NAME,
           r.REFERENCE_STATUS AS SOURCE_REF_STATUS, r.SOURCE_MEMBER_COUNT AS TOPIC_PARENT_MEMBERS,
           COALESCE(s.DIRECT_SOURCE_ID,IFF(r.REFERENCE_STATUS='REFERENCE_READY',r.TARGET_CONTENT_ID,NULL)) AS SOURCE_ID
    FROM authority_topic s
    LEFT JOIN nodes t ON t.KIND='TOPIC' AND t.CONTENT_ID=s.TOPIC_ID
    LEFT JOIN references_checked r ON r.OWNER_KIND='TOPIC' AND r.OWNER_CONTENT_ID=s.TOPIC_ID
      AND r.FIELD_NAME='SOURCE_REFERENCES'
), authority_branch AS (
    SELECT s.ATO_CONTENT_ID, s.ALLOCATED_CONTROL_CONTENT_ID, s.SSP_CONTROL_ID,
           s.CONTROL_STANDARD_CONTENT_ID, s.CONTROL_STANDARD_NAME, s.BRANCH,
           s.POLICY_LEVEL_1_CONTENT_ID, s.POLICY_LEVEL_1_NAME,
           s.POLICY_LEVEL_2_CONTENT_ID, s.POLICY_LEVEL_2_NAME,
           s.POLICY_LEVEL_3_CONTENT_ID, s.POLICY_LEVEL_3_NAME,
           s.SOURCE_ID AS AUTHORITATIVE_SOURCE_CONTENT_ID, src.DOC:SOURCE_NAME::VARCHAR AS AUTHORITATIVE_SOURCE_NAME,
           s.TOPIC_ID AS TOPIC_CONTENT_ID, s.TOPIC_NAME AS TOPIC_NAME,
           s.SECTION_ID AS SECTION_CONTENT_ID, s.SECTION_NAME,
           s.SS_ID AS SUBSECTION_CONTENT_ID, s.SS_NAME AS SUBSECTION_NAME,
           CASE WHEN s.BASE_STATUS <> 'BASE_READY' THEN s.BASE_STATUS
                WHEN s.DIRECT_AUTHORITY_STATUS IS DISTINCT FROM 'REFERENCE_READY'
                     THEN COALESCE(s.DIRECT_AUTHORITY_STATUS,'AUTHORITATIVE_REFERENCE_MISSING')
                WHEN s.DIRECT_AUTHORITY_KIND NOT IN ('SOURCE','TOPIC','SECTION','SUBSECTION') THEN 'AUTHORITATIVE_TARGET_DOMAIN_UNVERIFIED'
                WHEN (s.SS_ID IS NOT NULL AND s.SS_STATUS IS NULL)
                  OR (s.SECTION_ID IS NOT NULL AND s.SECTION_STATUS IS NULL)
                  OR (s.TOPIC_ID IS NOT NULL AND s.TOPIC_STATUS IS NULL)
                  OR s.SOURCE_ID IS NULL OR src.CONTENT_ID IS NULL THEN 'AUTHORITATIVE_RAW_TARGET_OR_PARENT_MISSING'
                WHEN (s.SS_ID IS NOT NULL AND s.SS_STATUS <> 'READY')
                  OR (s.SECTION_ID IS NOT NULL AND s.SECTION_STATUS <> 'READY')
                  OR (s.TOPIC_ID IS NOT NULL AND s.TOPIC_STATUS <> 'READY')
                  OR src.NODE_STATUS <> 'READY' THEN 'AUTHORITATIVE_STORED_SOURCE_UNVERIFIED'
                WHEN COALESCE(s.SECTION_REF_STATUS,'REFERENCE_READY') <> 'REFERENCE_READY'
                  OR COALESCE(s.TOPIC_REF_STATUS,'REFERENCE_READY') <> 'REFERENCE_READY'
                  OR COALESCE(s.SOURCE_REF_STATUS,'REFERENCE_READY') <> 'REFERENCE_READY' THEN 'AUTHORITATIVE_PARENT_REFERENCE_UNVERIFIED'
                WHEN COALESCE(s.SS_PARENT_MEMBERS,0)>1 OR COALESCE(s.SECTION_PARENT_MEMBERS,0)>1
                  OR COALESCE(s.TOPIC_PARENT_MEMBERS,0)>1 THEN 'MATCHED_AUTHORITATIVE_FIRST_PARENT_ONLY'
                ELSE IFF(s.BRANCH = 'POLICY_TO_AUTHORITATIVE_SOURCE',
                         'MATCHED_POLICY_TO_AUTHORITATIVE_REFERENCE','MATCHED_AUTHORITATIVE_REFERENCE') END AS RELATIONSHIP_STATUS,
           'RAW field ' || s.INPUT_FIELD || '; owner=' || s.AUTHORITY_OWNER_KIND || '/' || COALESCE(s.AUTHORITY_OWNER_ID,'none') || '; reference index=' || COALESCE(s.REFERENCE_INDEX::VARCHAR,'none')
           || '; direct target=' || COALESCE(s.DIRECT_AUTHORITY_ID,'none')
           || '; reverse publication parents use array member [0]'
           || '; Subsection/Section/Topic parent member counts=' || COALESCE(s.SS_PARENT_MEMBERS::VARCHAR,'n/a')
           || '/' || COALESCE(s.SECTION_PARENT_MEMBERS::VARCHAR,'n/a')
           || '/' || COALESCE(s.TOPIC_PARENT_MEMBERS::VARCHAR,'n/a')
           || '; Allocation AUTHORIZATION_PACKAGE member count=' || COALESCE(s.ALLOCATION_OWNER_MEMBER_COUNT::VARCHAR,'see policy context')
           || '; Allocation stored rows/JSON versions=' || COALESCE(s.ALLOCATION_STORED_ROWS::VARCHAR,'see policy context')
           || '/' || COALESCE(s.ALLOCATION_JSON_VERSIONS::VARCHAR,'see policy context')
           || '; Standard stored rows/JSON versions=' || COALESCE(s.STANDARD_STORED_ROWS::VARCHAR,'see policy context')
           || '/' || COALESCE(s.STANDARD_JSON_VERSIONS::VARCHAR,'see policy context')
           || IFF(s.POLICY_CONTEXT_NOTE IS NOT NULL,'; policy context: ' || s.POLICY_CONTEXT_NOTE,'') AS EVIDENCE_NOTE
    FROM authority_source s
    LEFT JOIN nodes src ON src.KIND='SOURCE' AND src.CONTENT_ID=s.SOURCE_ID
), final_rows AS (
    SELECT * FROM policy_branch
    UNION ALL
    SELECT * FROM authority_branch
)
SELECT ATO_CONTENT_ID, ALLOCATED_CONTROL_CONTENT_ID, SSP_CONTROL_ID,
       CONTROL_STANDARD_CONTENT_ID, CONTROL_STANDARD_NAME, BRANCH,
       POLICY_LEVEL_1_CONTENT_ID, POLICY_LEVEL_1_NAME,
       POLICY_LEVEL_2_CONTENT_ID, POLICY_LEVEL_2_NAME,
       POLICY_LEVEL_3_CONTENT_ID, POLICY_LEVEL_3_NAME,
       AUTHORITATIVE_SOURCE_CONTENT_ID, AUTHORITATIVE_SOURCE_NAME,
       TOPIC_CONTENT_ID, TOPIC_NAME, SECTION_CONTENT_ID, SECTION_NAME,
       SUBSECTION_CONTENT_ID, SUBSECTION_NAME, RELATIONSHIP_STATUS, EVIDENCE_NOTE
FROM final_rows
ORDER BY ATO_CONTENT_ID, ALLOCATED_CONTROL_CONTENT_ID, CONTROL_STANDARD_CONTENT_ID,
         BRANCH, POLICY_LEVEL_3_CONTENT_ID, POLICY_LEVEL_2_CONTENT_ID,
         POLICY_LEVEL_1_CONTENT_ID, SUBSECTION_CONTENT_ID, SECTION_CONTENT_ID,
         TOPIC_CONTENT_ID, AUTHORITATIVE_SOURCE_CONTENT_ID, EVIDENCE_NOTE
LIMIT 500;

