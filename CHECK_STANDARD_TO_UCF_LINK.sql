-- Read-only Snowflake query with the 03.01.01 candidate pair prefilled.
-- Package trace: DT-IA-001. Rev 2 Archer workbook candidate: DT-IA-001.01.
-- Checks one direct Related Control Standards reference in both directions.
-- RAW counts include stored versions. A conflict needs source-version review.
-- Saved counts use the Authoritative Sources Catalog route, where the property is mapped.
WITH input_ids AS (
    SELECT '876783' AS PACKAGE_ID,
           '7250382'     AS UCF_ID
), directions AS (
    SELECT 'PACKAGE_TO_UCF' AS DIRECTION, PACKAGE_ID AS FROM_ID, UCF_ID AS TO_ID FROM input_ids
    UNION ALL
    SELECT 'UCF_TO_PACKAGE', UCF_ID, PACKAGE_ID FROM input_ids
), raw_docs AS (
    SELECT CONTENT_ID::VARCHAR AS STANDARD_ID,
           TRY_PARSE_JSON(CURATED_JSON::VARCHAR, 's') AS DOC
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_STANDARDS_RAW
    WHERE CONTENT_ID::VARCHAR IN (SELECT FROM_ID FROM directions)
), raw_fields AS (
    SELECT STANDARD_ID, DOC, DOC:RELATED_CONTROL_STANDARDS AS REFS
    FROM raw_docs
), raw_records AS (
    SELECT STANDARD_ID,
           COUNT(*) AS STORED_ROWS,
           COUNT_IF(IS_OBJECT(DOC)) AS READABLE_ROWS,
           COUNT(DISTINCT IFF(IS_OBJECT(DOC), COALESCE(TO_JSON(REFS), '<MISSING>'), NULL)) AS FIELD_VERSIONS
    FROM raw_fields
    GROUP BY STANDARD_ID
), raw_members AS (
    SELECT f.STANDARD_ID,
           IFF(IS_OBJECT(m.VALUE), GET_IGNORE_CASE(AS_OBJECT(m.VALUE), 'ContentId'), m.VALUE)::VARCHAR AS TARGET_ID,
           GET_IGNORE_CASE(AS_OBJECT(m.VALUE), 'LevelId')::VARCHAR AS TARGET_LEVEL,
           GET_IGNORE_CASE(AS_OBJECT(m.VALUE), 'ModuleId')::VARCHAR AS TARGET_MODULE
    FROM raw_fields f,
         LATERAL FLATTEN(INPUT => IFF(IS_ARRAY(f.REFS), AS_ARRAY(f.REFS), ARRAY_CONSTRUCT(f.REFS))) m
), raw_matches AS (
    SELECT d.DIRECTION, COUNT(*) AS PAIR_MEMBERS,
           COUNT_IF(COALESCE(NULLIF(m.TARGET_LEVEL, 'null'), '41') <> '41'
                 OR COALESCE(NULLIF(m.TARGET_MODULE, 'null'), '66') <> '66') AS DOMAIN_CONFLICTS
    FROM directions d
    JOIN raw_members m ON m.STANDARD_ID = d.FROM_ID AND m.TARGET_ID = d.TO_ID
    GROUP BY d.DIRECTION
), saved_controls AS (
    SELECT PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS CONTROL_KEY,
           TRY_PARSE_JSON(METADATA_JSON::VARCHAR, 's') AS DOC
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT
    WHERE SOURCE_SYSTEM_NAME = 'ARCHER'
      AND SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW'
      AND ELEMENT_TYPE = 'controls'
), saved_ids AS (
    SELECT c.CONTROL_KEY, MIN(p.VALUE:value::VARCHAR) AS STANDARD_ID
    FROM saved_controls c, LATERAL FLATTEN(INPUT => c.DOC:props) p
    WHERE p.VALUE:name::VARCHAR = 'archer-content-id'
      AND (p.VALUE:ns IS NULL OR COALESCE(IS_NULL_VALUE(p.VALUE:ns), FALSE))
    GROUP BY c.CONTROL_KEY
    HAVING COUNT(*) = 1
), saved_placements AS (
    SELECT d.DIRECTION, COUNT(*) AS CONTROL_PLACEMENTS
    FROM directions d JOIN saved_ids i ON i.STANDARD_ID = d.FROM_ID
    GROUP BY d.DIRECTION
), saved_property AS (
    SELECT d.DIRECTION, d.TO_ID, c.CONTROL_KEY,
           TRY_PARSE_JSON(p.VALUE:value::VARCHAR, 's') AS REFS
    FROM directions d
    JOIN saved_ids i ON i.STANDARD_ID = d.FROM_ID
    JOIN saved_controls c ON c.CONTROL_KEY = i.CONTROL_KEY,
         LATERAL FLATTEN(INPUT => c.DOC:props) p
    WHERE p.VALUE:name::VARCHAR = 'related-control-standards'
      AND p.VALUE:ns::VARCHAR = 'urn:archer:source:v1'
), saved_matches AS (
    SELECT s.DIRECTION,
           COUNT(DISTINCT IFF(m.VALUE:ContentId::VARCHAR = s.TO_ID
                              AND m.VALUE:ModuleId::VARCHAR = '66', s.CONTROL_KEY, NULL)) AS LINK_PLACEMENTS,
           COUNT(DISTINCT IFF(m.VALUE:ContentId::VARCHAR = s.TO_ID
                              AND m.VALUE:ModuleId::VARCHAR IS DISTINCT FROM '66', s.CONTROL_KEY, NULL)) AS DOMAIN_CONFLICTS
    FROM saved_property s, LATERAL FLATTEN(INPUT => AS_ARRAY(s.REFS)) m
    GROUP BY s.DIRECTION
)
SELECT d.DIRECTION, d.FROM_ID AS FROM_STANDARD_CONTENT_ID, d.TO_ID AS TO_STANDARD_CONTENT_ID,
       CASE WHEN NOT REGEXP_LIKE(d.FROM_ID, '[1-9][0-9]*') OR NOT REGEXP_LIKE(d.TO_ID, '[1-9][0-9]*')
                  OR d.FROM_ID = d.TO_ID THEN 'ENTER_TWO_DISTINCT_ARCHER_CONTENT_IDS'
            WHEN src.STANDARD_ID IS NULL THEN 'FROM_STANDARD_MISSING_IN_RAW'
            WHEN tgt.STANDARD_ID IS NULL THEN 'TO_STANDARD_MISSING_IN_RAW'
            WHEN COALESCE(src.READABLE_ROWS, 0) <> src.STORED_ROWS THEN 'FROM_STANDARD_HAS_UNREADABLE_RAW_ROWS'
            WHEN COALESCE(tgt.READABLE_ROWS, 0) = 0 THEN 'TO_STANDARD_RAW_UNREADABLE'
            WHEN src.FIELD_VERSIONS > 1 THEN 'RELATED_FIELD_DIFFERS_ACROSS_RAW_VERSIONS'
            WHEN COALESCE(r.DOMAIN_CONFLICTS, 0) > 0 THEN 'PAIR_REFERENCE_DOMAIN_CONFLICT'
            WHEN COALESCE(r.PAIR_MEMBERS, 0) > 0 THEN 'PAIR_REFERENCE_FOUND'
            ELSE 'PAIR_REFERENCE_NOT_FOUND' END AS RAW_STATUS,
       CASE WHEN NOT REGEXP_LIKE(d.FROM_ID, '[1-9][0-9]*') OR NOT REGEXP_LIKE(d.TO_ID, '[1-9][0-9]*')
                  OR d.FROM_ID = d.TO_ID THEN 'ENTER_TWO_DISTINCT_ARCHER_CONTENT_IDS'
            WHEN COALESCE(p.CONTROL_PLACEMENTS, 0) = 0 THEN 'FROM_STANDARD_NOT_IN_AUTHORITATIVE_CATALOG'
            WHEN COALESCE(s.DOMAIN_CONFLICTS, 0) > 0 THEN 'SAVED_PAIR_REFERENCE_DOMAIN_CONFLICT'
            WHEN COALESCE(s.LINK_PLACEMENTS, 0) > 0 THEN 'PAIR_REFERENCE_FOUND'
            ELSE 'PAIR_REFERENCE_NOT_FOUND' END AS OSCAL_STATUS,
       COALESCE(src.STORED_ROWS, 0) AS FROM_RAW_ROWS,
       COALESCE(src.FIELD_VERSIONS, 0) AS RAW_FIELD_VERSIONS,
       COALESCE(p.CONTROL_PLACEMENTS, 0) AS SAVED_FROM_PLACEMENTS,
       COALESCE(s.LINK_PLACEMENTS, 0) AS SAVED_LINK_PLACEMENTS
FROM directions d
LEFT JOIN raw_records src ON src.STANDARD_ID = d.FROM_ID
LEFT JOIN raw_records tgt ON tgt.STANDARD_ID = d.TO_ID
LEFT JOIN raw_matches r ON r.DIRECTION = d.DIRECTION
LEFT JOIN saved_placements p ON p.DIRECTION = d.DIRECTION
LEFT JOIN saved_matches s ON s.DIRECTION = d.DIRECTION
ORDER BY d.DIRECTION;
