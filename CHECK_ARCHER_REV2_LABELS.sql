-- Run the whole read-only query in Snowflake DEV. No edits are needed.
-- Searches for explicit Rev 2 / Revision 2 text in selected RAW fields.
-- Counts distinct Archer Content IDs per field across stored RAW rows.
-- A label alone does not establish a Standard reference or publication relationship.
WITH raw_documents AS (
    SELECT 'CONTROL_STANDARD' AS RECORD_TYPE, CONTENT_ID::VARCHAR AS CONTENT_ID,
           TRY_PARSE_JSON(CURATED_JSON::VARCHAR, 's') AS DOC
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_STANDARDS_RAW
    UNION ALL
    SELECT 'ALLOCATED_CONTROL', CONTENT_ID::VARCHAR, TRY_PARSE_JSON(CURATED_JSON::VARCHAR, 's')
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_ALLOCATED_CONTROLS_CONTROL_RAW
    UNION ALL
    SELECT 'AUTHORIZATION_PACKAGE', CONTENT_ID::VARCHAR, TRY_PARSE_JSON(CURATED_JSON::VARCHAR, 's')
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
    UNION ALL
    SELECT 'AUTHORITATIVE_SOURCE', CONTENT_ID::VARCHAR, TRY_PARSE_JSON(CURATED_JSON::VARCHAR, 's')
    FROM RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
), fields_to_check (DISPLAY_ORDER, RECORD_TYPE, FIELD_NAME) AS (
    SELECT * FROM VALUES
        (1, 'CONTROL_STANDARD', 'CONTROL_STANDARD_NAME'),
        (2, 'CONTROL_STANDARD', 'BASELINE_VERSION_COMBO_TEXT'),
        (3, 'CONTROL_STANDARD', 'BASELINE_VERSION_COMBO'),
        (4, 'ALLOCATED_CONTROL', 'CONTROL_NUMBER'),
        (5, 'ALLOCATED_CONTROL', 'CONTROL_SET_VERSION_NUMBER'),
        (6, 'AUTHORIZATION_PACKAGE', 'CONTROL_SET_VERSION_NUMBER'),
        (7, 'AUTHORITATIVE_SOURCE', 'SOURCE_NAME'),
        (8, 'AUTHORITATIVE_SOURCE', 'SOURCE_VERSION')
), field_values AS (
    SELECT f.DISPLAY_ORDER, r.CONTENT_ID,
           NULLIF(TRIM(GET(AS_OBJECT(r.DOC), f.FIELD_NAME)::VARCHAR), '') AS FIELD_VALUE
    FROM fields_to_check f
    JOIN raw_documents r ON r.RECORD_TYPE = f.RECORD_TYPE
), checked AS (
    SELECT *, COALESCE(REGEXP_INSTR(
        FIELD_VALUE, '(^|[^[:alnum:]])(REVISION|REV[.]?)[[:space:]_:-]*2([^[:alnum:]]|$)',
        1, 1, 0, 'i') > 0, FALSE) AS HAS_REV_2
    FROM field_values
), counts AS (
    SELECT DISPLAY_ORDER, COUNT(DISTINCT CONTENT_ID) AS RECORDS_CHECKED,
           COUNT(DISTINCT IFF(FIELD_VALUE IS NOT NULL AND FIELD_VALUE <> 'null', CONTENT_ID, NULL))
               AS RECORDS_WITH_FIELD_VALUE,
           COUNT(DISTINCT IFF(HAS_REV_2, CONTENT_ID, NULL)) AS RECORDS_WITH_REV_2_LABEL
    FROM checked
    GROUP BY DISPLAY_ORDER
), matching_values AS (
    SELECT DISTINCT DISPLAY_ORDER, CONTENT_ID, FIELD_VALUE
    FROM checked
    WHERE HAS_REV_2
), sample_matches AS (
    SELECT DISPLAY_ORDER, CONTENT_ID, FIELD_VALUE
    FROM matching_values
    QUALIFY ROW_NUMBER() OVER (PARTITION BY DISPLAY_ORDER ORDER BY CONTENT_ID, FIELD_VALUE) <= 5
), examples AS (
    SELECT DISPLAY_ORDER,
           ARRAY_AGG(OBJECT_CONSTRUCT('CONTENT_ID', CONTENT_ID, 'VALUE', LEFT(FIELD_VALUE, 500)))
             WITHIN GROUP (ORDER BY CONTENT_ID, FIELD_VALUE) AS EXAMPLE_RECORDS
    FROM sample_matches
    GROUP BY DISPLAY_ORDER
)
SELECT f.RECORD_TYPE, f.FIELD_NAME,
       COALESCE(c.RECORDS_CHECKED, 0) AS RECORDS_CHECKED,
       COALESCE(c.RECORDS_WITH_FIELD_VALUE, 0) AS RECORDS_WITH_FIELD_VALUE,
       COALESCE(c.RECORDS_WITH_REV_2_LABEL, 0) AS RECORDS_WITH_REV_2_LABEL,
       COALESCE(e.EXAMPLE_RECORDS, ARRAY_CONSTRUCT()) AS EXAMPLE_RECORDS
FROM fields_to_check f
LEFT JOIN counts c ON c.DISPLAY_ORDER = f.DISPLAY_ORDER
LEFT JOIN examples e ON e.DISPLAY_ORDER = f.DISPLAY_ORDER
ORDER BY f.DISPLAY_ORDER;
