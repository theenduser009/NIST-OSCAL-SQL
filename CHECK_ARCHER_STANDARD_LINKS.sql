-- Archer RAW only. Run the whole read-only statement in Snowflake.
-- Reads both known Control Standards, retaining each stored row.
-- An explicit reference path is a clue to the linking field. A shared UCF ID
-- is a candidate join key until its meaning and uniqueness are confirmed.
WITH pair (CONTENT_ID, STANDARD_SIDE, OTHER_CONTENT_ID) AS (
    SELECT * FROM VALUES ('876783', 'PACKAGE', '7250382'), ('7250382', 'REV_2', '876783')
), raw_documents AS (
    SELECT p.*, TRY_PARSE_JSON(r.CURATED_JSON::VARCHAR, 's') AS DOC,
           COUNT(r.CONTENT_ID) OVER (PARTITION BY p.CONTENT_ID) AS STORED_ROWS
    FROM pair p
    LEFT JOIN RTX_RAW_DEV.ES_ESC_GRC.ARCHER_CONTENT_CONTROL_STANDARDS_RAW r
      ON r.CONTENT_ID::VARCHAR = p.CONTENT_ID
), raw_rows AS (
    SELECT d.*, ROW_NUMBER() OVER (PARTITION BY d.CONTENT_ID ORDER BY TO_JSON(d.DOC)) AS ROW_NUMBER_FOR_ID
    FROM raw_documents d
), object_references AS (
    -- Find explicit ContentId objects anywhere in the two source documents.
    SELECT r.CONTENT_ID, r.ROW_NUMBER_FOR_ID,
           ARRAY_AGG(DISTINCT f.PATH) WITHIN GROUP (ORDER BY f.PATH) AS MATCHING_OBJECT_PATHS
    FROM raw_rows r, LATERAL FLATTEN(INPUT => r.DOC, RECURSIVE => TRUE) f
    WHERE GET_IGNORE_CASE(AS_OBJECT(f.VALUE), 'ContentId')::VARCHAR = r.OTHER_CONTENT_ID
      AND COALESCE(NULLIF(GET_IGNORE_CASE(AS_OBJECT(f.VALUE), 'LevelId')::VARCHAR, 'null'), '41') = '41'
      AND COALESCE(NULLIF(GET_IGNORE_CASE(AS_OBJECT(f.VALUE), 'ModuleId')::VARCHAR, 'null'), '66') = '66'
    GROUP BY r.CONTENT_ID, r.ROW_NUMBER_FOR_ID
), reference_fields AS (
    SELECT r.CONTENT_ID, r.OTHER_CONTENT_ID, r.ROW_NUMBER_FOR_ID, f.KEY AS FIELD_NAME, f.VALUE AS REFS
    FROM raw_rows r, LATERAL FLATTEN(INPUT => OBJECT_CONSTRUCT(
        'RELATED_CONTROL_STANDARDS', r.DOC:RELATED_CONTROL_STANDARDS,
        'CONTROL_STANDARDS_RELATED_CONTROL_REQUIREMENTS', r.DOC:CONTROL_STANDARDS_RELATED_CONTROL_REQUIREMENTS,
        'CONTROL_REQUIREMENTS_DPF_CONTROL_STANDARD', r.DOC:CONTROL_REQUIREMENTS_DPF_CONTROL_STANDARD,
        'RELATED_BASELINE_CONTROLS', r.DOC:RELATED_BASELINE_CONTROLS,
        'RELATED_ENHANCED_CONTROLS', r.DOC:RELATED_ENHANCED_CONTROLS
    )) f
), scalar_references AS (
    -- Bare IDs can be meaningful in reference fields. Do not scan unrelated
    -- numeric fields or substrings of descriptions for apparent matches.
    SELECT r.CONTENT_ID, r.ROW_NUMBER_FOR_ID,
           ARRAY_AGG(DISTINCT r.FIELD_NAME) WITHIN GROUP (ORDER BY r.FIELD_NAME) AS MATCHING_SCALAR_FIELDS
    FROM reference_fields r,
         LATERAL FLATTEN(INPUT => IFF(IS_ARRAY(r.REFS), AS_ARRAY(r.REFS), ARRAY_CONSTRUCT(r.REFS))) f
    WHERE TYPEOF(f.VALUE) IN ('VARCHAR', 'INTEGER', 'DECIMAL')
      AND f.VALUE::VARCHAR = r.OTHER_CONTENT_ID
    GROUP BY r.CONTENT_ID, r.ROW_NUMBER_FOR_ID
), ucf_members AS (
    SELECT DISTINCT r.CONTENT_ID, r.ROW_NUMBER_FOR_ID, TRIM(f.VALUE::VARCHAR) AS UCF_VALUE
    FROM raw_rows r,
         LATERAL FLATTEN(INPUT => IFF(IS_ARRAY(r.DOC:UCF_ID), AS_ARRAY(r.DOC:UCF_ID), ARRAY_CONSTRUCT(r.DOC:UCF_ID))) f
    WHERE TYPEOF(f.VALUE) IN ('VARCHAR', 'INTEGER', 'DECIMAL') AND TRIM(f.VALUE::VARCHAR) <> ''
), shared_ucf AS (
    SELECT x.CONTENT_ID, x.ROW_NUMBER_FOR_ID,
           ARRAY_AGG(DISTINCT x.UCF_VALUE) WITHIN GROUP (ORDER BY x.UCF_VALUE) AS SHARED_UCF_IDS
    FROM ucf_members x JOIN ucf_members y ON x.CONTENT_ID <> y.CONTENT_ID AND x.UCF_VALUE = y.UCF_VALUE
    GROUP BY x.CONTENT_ID, x.ROW_NUMBER_FOR_ID
)
SELECT r.STANDARD_SIDE, r.CONTENT_ID AS ARCHER_STANDARD_CONTENT_ID,
       r.DOC:CONTROL_STANDARD_NAME::VARCHAR AS CONTROL_STANDARD_NAME,
       r.STORED_ROWS, r.ROW_NUMBER_FOR_ID,
       CASE WHEN r.STORED_ROWS = 0 THEN 'RAW_RECORD_MISSING'
            WHEN NOT COALESCE(IS_OBJECT(r.DOC), FALSE) THEN 'RAW_JSON_UNREADABLE'
            WHEN r.STORED_ROWS > 1 THEN 'REVIEW_STORED_ROWS'
            ELSE 'RAW_RECORD_READ' END AS SOURCE_STATUS,
       r.DOC:UCF_ID AS UCF_ID,
       COALESCE(u.SHARED_UCF_IDS, ARRAY_CONSTRUCT()) AS SHARED_UCF_IDS,
       COALESCE(o.MATCHING_OBJECT_PATHS, ARRAY_CONSTRUCT()) AS DIRECT_REFERENCE_PATHS,
       COALESCE(s.MATCHING_SCALAR_FIELDS, ARRAY_CONSTRUCT()) AS BARE_ID_REFERENCE_FIELDS,
       r.DOC:CONTROL_STANDARDS_RELATED_CONTROL_REQUIREMENTS AS CONTROL_STANDARDS_RELATED_CONTROL_REQUIREMENTS,
       r.DOC:CONTROL_REFERENCE_ID AS CONTROL_REFERENCE_ID,
       r.DOC:NIST_800171_CONTROL_ID AS NIST_800171_CONTROL_ID,
       r.DOC:STANDARD_ID AS STANDARD_ID,
       r.DOC:ARCHER_STANDARD_ID AS ARCHER_STANDARD_ID
FROM raw_rows r
LEFT JOIN object_references o ON o.CONTENT_ID = r.CONTENT_ID AND o.ROW_NUMBER_FOR_ID = r.ROW_NUMBER_FOR_ID
LEFT JOIN scalar_references s ON s.CONTENT_ID = r.CONTENT_ID AND s.ROW_NUMBER_FOR_ID = r.ROW_NUMBER_FOR_ID
LEFT JOIN shared_ucf u ON u.CONTENT_ID = r.CONTENT_ID AND u.ROW_NUMBER_FOR_ID = r.ROW_NUMBER_FOR_ID
ORDER BY r.STANDARD_SIDE, r.ROW_NUMBER_FOR_ID;
