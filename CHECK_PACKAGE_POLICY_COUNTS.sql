-- Run the whole read-only statement in Snowflake. No settings are required.
-- Scope: all saved Archer Authorization Packages with SSP implemented requirements.
-- Count each referenced Standard once across packages, requirements, and Catalogs.
-- The SUMMARY row can be compared with the reported 324 / 259 / 65 counts.
-- STANDARD rows list the individual Standards and their saved Policy Catalog IDs.
-- A placement here requires a saved CONTAINS path from the Policy Catalog to the control.
-- This measures saved Catalog placement, distinct from the Standard's separate policy-hierarchy property.

WITH ssp_requirements AS (
    SELECT d.PK_OSCAL_SSP_ELEMENT_HASH AS REQUIREMENT_KEY,
           d.SOURCE_RECORD_ID::VARCHAR AS PACKAGE_CONTENT_ID,
           TRY_PARSE_JSON(d.METADATA_JSON::VARCHAR, 's') AS DOC
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_SSP_ELEMENT d
    WHERE d.SOURCE_SYSTEM_NAME = 'ARCHER'
      AND d.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW'
      AND d.ELEMENT_TYPE = 'implemented-requirements'
), dpf_properties AS (
    SELECT s.REQUIREMENT_KEY, s.PACKAGE_CONTENT_ID,
           TRY_PARSE_JSON(p.VALUE:value::VARCHAR, 's') AS DPF_JSON
    FROM ssp_requirements s, LATERAL FLATTEN(INPUT => AS_ARRAY(s.DOC:props)) p
    WHERE p.VALUE:name::VARCHAR = 'archer-control-standard-reference'
      AND p.VALUE:ns::VARCHAR = 'urn:archer:source:v1'
), dpf_members AS (
    SELECT p.REQUIREMENT_KEY, p.PACKAGE_CONTENT_ID,
           m.VALUE:ContentId::VARCHAR AS CONTROL_STANDARD_CONTENT_ID,
           m.VALUE:LevelId::VARCHAR AS DECLARED_LEVEL,
           m.VALUE:ModuleId::VARCHAR AS DECLARED_MODULE
    FROM dpf_properties p, LATERAL FLATTEN(INPUT => CASE
        WHEN IS_ARRAY(p.DPF_JSON) THEN AS_ARRAY(p.DPF_JSON)
        WHEN IS_OBJECT(p.DPF_JSON) THEN ARRAY_CONSTRUCT(p.DPF_JSON)
        ELSE ARRAY_CONSTRUCT() END) m
), valid_refs AS (
    SELECT DISTINCT REQUIREMENT_KEY, PACKAGE_CONTENT_ID, CONTROL_STANDARD_CONTENT_ID
    FROM dpf_members
    WHERE REGEXP_LIKE(CONTROL_STANDARD_CONTENT_ID, '[1-9][0-9]*')
      AND COALESCE(NULLIF(DECLARED_LEVEL, 'null'), '41') = '41'
      AND COALESCE(NULLIF(DECLARED_MODULE, 'null'), '66') = '66'
), package_standards AS (
    SELECT CONTROL_STANDARD_CONTENT_ID, COUNT(DISTINCT PACKAGE_CONTENT_ID) AS PACKAGES_REFERENCING_STANDARD
    FROM valid_refs
    GROUP BY CONTROL_STANDARD_CONTENT_ID
), catalog_controls AS (
    SELECT c.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS CONTROL_KEY,
           c.SOURCE_TABLE_NAME,
           c.SOURCE_RECORD_ID AS CATALOG_ROOT_CONTENT_ID,
           TRY_PARSE_JSON(c.METADATA_JSON::VARCHAR, 's') AS DOC
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT c
    WHERE c.SOURCE_SYSTEM_NAME = 'ARCHER'
      AND c.ELEMENT_TYPE = 'controls'
      AND c.SOURCE_TABLE_NAME IN (
          'ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW',
          'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_1_RAW',
          'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW',
          'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW'
      )
), catalog_identified AS (
    SELECT c.CONTROL_KEY, MIN(p.VALUE:value::VARCHAR) AS CONTROL_STANDARD_CONTENT_ID
    FROM catalog_controls c, LATERAL FLATTEN(INPUT => AS_ARRAY(c.DOC:props)) p
    WHERE p.VALUE:name::VARCHAR = 'archer-content-id'
      AND (p.VALUE:ns IS NULL OR COALESCE(IS_NULL_VALUE(p.VALUE:ns), FALSE))
    GROUP BY c.CONTROL_KEY
    HAVING COUNT(*) = 1 AND REGEXP_LIKE(MIN(p.VALUE:value::VARCHAR), '[1-9][0-9]*')
), scoped_controls AS (
    SELECT c.CONTROL_KEY, c.SOURCE_TABLE_NAME, c.CATALOG_ROOT_CONTENT_ID,
           i.CONTROL_STANDARD_CONTENT_ID
    FROM catalog_identified i
    JOIN package_standards s ON s.CONTROL_STANDARD_CONTENT_ID = i.CONTROL_STANDARD_CONTENT_ID
    JOIN catalog_controls c ON c.CONTROL_KEY = i.CONTROL_KEY
), policy_roots AS (
    SELECT c.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH AS ROOT_KEY, c.SOURCE_TABLE_NAME,
           c.SOURCE_RECORD_ID AS POLICY_CONTENT_ID
    FROM RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT c
    WHERE c.SOURCE_SYSTEM_NAME = 'ARCHER' AND c.ELEMENT_TYPE = 'catalog'
      AND c.SOURCE_TABLE_NAME IN ('ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW',
                                  'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW')
), policy_owners AS (
    SELECT ROOT_KEY AS OWNER_KEY, SOURCE_TABLE_NAME, POLICY_CONTENT_ID FROM policy_roots
    UNION ALL
    SELECT DISTINCT g.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH, r.SOURCE_TABLE_NAME, r.POLICY_CONTENT_ID
    FROM policy_roots r
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f
      ON f.FK_SOURCE_ELEMENT_HASH = r.ROOT_KEY AND f.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.DIM_OSCAL_CATALOG_ELEMENT g
      ON g.PK_DIM_OSCAL_CATALOG_ELEMENT_HASH = f.FK_TARGET_ELEMENT_HASH
     AND g.SOURCE_SYSTEM_NAME = 'ARCHER' AND g.ELEMENT_TYPE = 'groups'
     AND g.SOURCE_TABLE_NAME = r.SOURCE_TABLE_NAME AND g.SOURCE_RECORD_ID = r.POLICY_CONTENT_ID
), policy_membership AS (
    SELECT DISTINCT c.CONTROL_STANDARD_CONTENT_ID, c.CATALOG_ROOT_CONTENT_ID::VARCHAR AS POLICY_CONTENT_ID,
           IFF(c.SOURCE_TABLE_NAME = 'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW', 2, 3) AS POLICY_LEVEL
    FROM scoped_controls c
    JOIN RTX_ENTERPRISESERVICES_DEV.ES_ESC_GRC_CURATED.FACT_OSCAL_CATALOG_DEPENDENCY f
      ON f.FK_TARGET_ELEMENT_HASH = c.CONTROL_KEY AND f.DEPENDENCY_TYPE = 'CONTAINS'
    JOIN policy_owners owner
      ON owner.OWNER_KEY = f.FK_SOURCE_ELEMENT_HASH
     AND owner.SOURCE_TABLE_NAME = c.SOURCE_TABLE_NAME
     AND owner.POLICY_CONTENT_ID = c.CATALOG_ROOT_CONTENT_ID
    WHERE c.SOURCE_TABLE_NAME IN ('ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW',
                                  'ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW')
), membership_by_standard AS (
    SELECT CONTROL_STANDARD_CONTENT_ID,
           LISTAGG(DISTINCT IFF(POLICY_LEVEL = 2, POLICY_CONTENT_ID, NULL), ', ') AS LEVEL_2_POLICY_CONTENT_IDS,
           LISTAGG(DISTINCT IFF(POLICY_LEVEL = 3, POLICY_CONTENT_ID, NULL), ', ') AS LEVEL_3_POLICY_CONTENT_IDS,
           COUNT_IF(POLICY_LEVEL = 2) AS LEVEL_2_COUNT,
           COUNT_IF(POLICY_LEVEL = 3) AS LEVEL_3_COUNT
    FROM policy_membership
    GROUP BY CONTROL_STANDARD_CONTENT_ID
), placed_standards AS (
    SELECT DISTINCT CONTROL_STANDARD_CONTENT_ID FROM scoped_controls
), detail AS (
    SELECT s.*, m.LEVEL_2_POLICY_CONTENT_IDS, m.LEVEL_3_POLICY_CONTENT_IDS,
           CASE WHEN COALESCE(m.LEVEL_3_COUNT, 0) > 0 THEN 'HAS_LEVEL_3'
                WHEN COALESCE(m.LEVEL_2_COUNT, 0) > 0 THEN 'LEVEL_2_NO_LEVEL_3'
                WHEN p.CONTROL_STANDARD_CONTENT_ID IS NULL THEN 'STANDARD_NOT_FOUND_IN_SAVED_CATALOGS'
                ELSE 'NO_SAVED_LEVEL_2_OR_LEVEL_3_PLACEMENT' END AS POLICY_RESULT
    FROM package_standards s
    LEFT JOIN membership_by_standard m ON m.CONTROL_STANDARD_CONTENT_ID = s.CONTROL_STANDARD_CONTENT_ID
    LEFT JOIN placed_standards p ON p.CONTROL_STANDARD_CONTENT_ID = s.CONTROL_STANDARD_CONTENT_ID
), summary AS (
    SELECT COUNT(*) AS DISTINCT_PACKAGE_STANDARDS,
           COALESCE(COUNT_IF(POLICY_RESULT = 'LEVEL_2_NO_LEVEL_3'), 0) AS LEVEL_2_NO_LEVEL_3,
           COALESCE(COUNT_IF(POLICY_RESULT = 'HAS_LEVEL_3'), 0) AS HAS_LEVEL_3,
           COALESCE(COUNT_IF(POLICY_RESULT = 'NO_SAVED_LEVEL_2_OR_LEVEL_3_PLACEMENT'), 0) AS NEITHER_LEVEL_2_NOR_LEVEL_3,
           COALESCE(COUNT_IF(POLICY_RESULT = 'STANDARD_NOT_FOUND_IN_SAVED_CATALOGS'), 0) AS STANDARD_NOT_IN_CATALOGS
    FROM detail
), scope_counts AS (
    SELECT COUNT(DISTINCT PACKAGE_CONTENT_ID) AS SSP_PACKAGES,
           COUNT(DISTINCT REQUIREMENT_KEY) AS SSP_REQUIREMENTS
    FROM ssp_requirements
), reference_counts AS (
    SELECT COUNT(DISTINCT REQUIREMENT_KEY) AS SSP_REQUIREMENTS_WITH_VALID_DPF FROM valid_refs
), report AS (
    SELECT 'SUMMARY' AS ROW_TYPE, NULL::VARCHAR AS CONTROL_STANDARD_CONTENT_ID,
           NULL::VARCHAR AS POLICY_RESULT, NULL::NUMBER AS PACKAGES_REFERENCING_STANDARD,
           NULL::VARCHAR AS LEVEL_2_POLICY_CONTENT_IDS, NULL::VARCHAR AS LEVEL_3_POLICY_CONTENT_IDS,
           s.DISTINCT_PACKAGE_STANDARDS, s.LEVEL_2_NO_LEVEL_3, s.HAS_LEVEL_3,
           s.NEITHER_LEVEL_2_NOR_LEVEL_3, s.STANDARD_NOT_IN_CATALOGS,
           c.SSP_PACKAGES, c.SSP_REQUIREMENTS, r.SSP_REQUIREMENTS_WITH_VALID_DPF
    FROM summary s CROSS JOIN scope_counts c CROSS JOIN reference_counts r
    UNION ALL
    SELECT 'STANDARD', CONTROL_STANDARD_CONTENT_ID, POLICY_RESULT, PACKAGES_REFERENCING_STANDARD,
           LEVEL_2_POLICY_CONTENT_IDS, LEVEL_3_POLICY_CONTENT_IDS,
           NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL
    FROM detail
)
SELECT * FROM report
ORDER BY IFF(ROW_TYPE = 'SUMMARY', 0, 1), POLICY_RESULT, CONTROL_STANDARD_CONTENT_ID;
