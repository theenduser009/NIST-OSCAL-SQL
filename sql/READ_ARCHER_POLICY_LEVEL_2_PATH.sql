-- Select the Archer RAW database and schema in the Snowflake worksheet.
-- Run the read-only statement, then filter the results by Level 2 Content ID.
WITH level_2 AS (
    SELECT CONTENT_ID, TRY_PARSE_JSON(CURATED_JSON::VARCHAR) AS doc
    FROM ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW
), references_to_level_3 AS (
    SELECT
        l2.CONTENT_ID AS LEVEL_2_CONTENT_ID,
        l2.doc:POLICY_LEVEL_2_NAME::VARCHAR AS LEVEL_2_NAME,
        l2.doc:POLICY_LEVEL_1_REFERENCE AS LEVEL_1_REFERENCE,
        r.value:ContentId::VARCHAR AS LEVEL_3_CONTENT_ID,
        r.value:LevelId::VARCHAR AS REFERENCE_LEVEL_ID
    FROM level_2 l2,
         LATERAL FLATTEN(INPUT => TO_ARRAY(l2.doc:POLICY_LEVEL_3_REFERENCE), OUTER => TRUE) r
), level_3 AS (
    SELECT CONTENT_ID, TRY_PARSE_JSON(CURATED_JSON::VARCHAR) AS doc
    FROM ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW
)
SELECT
    ref.*,
    COALESCE(NULLIF(l3.doc:POLICY_LEVEL_3_NAME::VARCHAR, 'null'),
             NULLIF(l3.doc:POLICY__LEVEL_3_NAME::VARCHAR, 'null')) AS LEVEL_3_NAME,
    OBJECT_PICK(AS_OBJECT(l3.doc),
        'AUTHORITATIVE_SOURCES',
        'AUTHORITATIVE_SOURCES_POLICY_LEVEL_3_FROM_SECTION_AND_SUBSECTION_LEVELS',
        'AUTHORITATIVE_SOURCES_POLICY_LEVEL_3__FROM_SECTION_AND_SUBSECTION_LEVELS',
        'AUTHORITATIVE_SOURCES_POLICY_LEVEL_3_FROM_SECTION_LEVEL_AND_BELOW',
        'AUTHORITATIVE_SOURCES_POLICY_LEVEL_3_FROM_TOPIC_SECTION_AND_SUBSECTION_LEVELS'
    ) AS LEVEL_3_SOURCE_REFERENCES,
    CASE
        WHEN ref.LEVEL_3_CONTENT_ID IS NULL THEN 'NO_LEVEL_3_CONTENT_ID'
        WHEN COALESCE(NULLIF(ref.REFERENCE_LEVEL_ID, 'null'), '5') <> '5' THEN 'REFERENCE_LEVEL_MISMATCH'
        WHEN l3.CONTENT_ID IS NULL THEN 'LEVEL_3_RECORD_MISSING'
        ELSE 'LEVEL_3_RECORD_FOUND'
    END AS LINK_STATUS
FROM references_to_level_3 ref
LEFT JOIN level_3 l3
  ON l3.CONTENT_ID::VARCHAR = ref.LEVEL_3_CONTENT_ID
 AND COALESCE(NULLIF(ref.REFERENCE_LEVEL_ID, 'null'), '5') = '5'
ORDER BY ref.LEVEL_2_CONTENT_ID, ref.LEVEL_3_CONTENT_ID;
