-- Select the Archer RAW database and schema in the Snowflake worksheet.
-- Run this read-only SELECT and filter the results by CONTENT_ID or STANDARD_NAME.
SELECT
    CONTENT_ID,
    doc:CONTROL_STANDARD_NAME::VARCHAR AS STANDARD_NAME,
    doc:POLICY_HIERARCHY_LEVEL_1_2_3 AS POLICY_REFERENCES,
    doc:AUTHORITATIVE_SOURCES AS PUBLICATION_REFERENCES,
    doc:UCF_ID AS STANDARD_UCF_ID
FROM (
    SELECT CONTENT_ID, TRY_PARSE_JSON(CURATED_JSON::VARCHAR) AS doc
    FROM ARCHER_CONTENT_CONTROL_STANDARDS_RAW
) AS standard_record;
