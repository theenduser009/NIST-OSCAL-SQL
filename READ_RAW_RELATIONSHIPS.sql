-- Select the database/schema containing your Archer RAW tables.
-- Run one numbered SELECT at a time. All statements are read-only.
-- Each query shows up to 100 stored rows; this is not an all-record link audit.
-- CURATED_JSON is the normalized input used by the mapper, not the original Archer export.
-- Repeated Content IDs may be stored versions. No latest-version rule is applied here.
-- Reference values are shown unchanged; a populated reference does not prove its target exists.

-- 1. ATO package: forward allocation list. This is not the mapper's ownership rule.
SELECT CONTENT_ID AS ATO_CONTENT_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):AUTHORIZATION_PACKAGE_NAME AS AUTHORIZATION_PACKAGE_NAME,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):ALLOCATED_CONTROLS AS ALLOCATED_CONTROLS
FROM ARCHER_CONTENT_AUTHORIZATION_PACKAGE_RAW
ORDER BY CONTENT_ID
LIMIT 100;

-- 2. Allocated Control: package owner and Standard reference.
-- The current mapper uses the first AUTHORIZATION_PACKAGE member for ownership.
SELECT CONTENT_ID AS ALLOCATED_CONTROL_CONTENT_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):ALLOCATED_CONTROL_ID AS ALLOCATED_CONTROL_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):CONTROL_NUMBER AS CONTROL_NUMBER,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):AUTHORIZATION_PACKAGE AS AUTHORIZATION_PACKAGE,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):DIGITAL_POLICY_FRAMEWORK_DPF_REFERENCE AS DIGITAL_POLICY_FRAMEWORK_DPF_REFERENCE
FROM ARCHER_CONTENT_ALLOCATED_CONTROLS_CONTROL_RAW
ORDER BY CONTENT_ID
LIMIT 100;

-- 3. Control Standard: policy, publication, and related-Standard references.
-- RELATED_CONTROL_STANDARDS is not automatically a decomposition/coverage relationship.
SELECT CONTENT_ID AS CONTROL_STANDARD_CONTENT_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):CONTROL_STANDARD_NAME AS CONTROL_STANDARD_NAME,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):POLICY_HIERARCHY_LEVEL_1_2_3 AS POLICY_HIERARCHY_LEVEL_1_2_3,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):AUTHORITATIVE_SOURCES AS AUTHORITATIVE_SOURCES,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):RELATED_CONTROL_STANDARDS AS RELATED_CONTROL_STANDARDS
FROM ARCHER_CONTENT_CONTROL_STANDARDS_RAW
ORDER BY CONTENT_ID
LIMIT 100;

-- 4. Policy Level 1: other policy levels, Standards, and publication references.
SELECT CONTENT_ID AS POLICY_CONTENT_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):POLICY_LEVEL_1_NAME AS POLICY_LEVEL_1_NAME,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):POLICY_LEVEL_2_REFERENCE AS POLICY_LEVEL_2_REFERENCE,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):POLICY_LEVEL_3_REFERENCE AS POLICY_LEVEL_3_REFERENCE,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):CONTROL_STANDARDS AS CONTROL_STANDARDS,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):AUTHORITATIVE_SOURCE_REFERENCES AS AUTHORITATIVE_SOURCE_REFERENCES
FROM ARCHER_CONTENT_POLICIES_POLICY_LEVEL_1_RAW
ORDER BY CONTENT_ID
LIMIT 100;

-- 5. Policy Level 2: preserve its two distinct Standard-reference fields.
-- No Level-2-to-publication field is assumed here.
SELECT CONTENT_ID AS POLICY_CONTENT_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):POLICY_LEVEL_2_NAME AS POLICY_LEVEL_2_NAME,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):POLICY_LEVEL_1_REFERENCE AS POLICY_LEVEL_1_REFERENCE,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):POLICY_LEVEL_3_REFERENCE AS POLICY_LEVEL_3_REFERENCE,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):CONTROL_STANDARDS AS CONTROL_STANDARDS,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):CONTROL_STANDARD_REQUIREMENTS AS CONTROL_STANDARD_REQUIREMENTS
FROM ARCHER_CONTENT_POLICIES_POLICY_LEVEL_2_RAW
ORDER BY CONTENT_ID
LIMIT 100;

-- 6. Policy Level 3: do not require a Level 1 parent to inspect this record.
SELECT CONTENT_ID AS POLICY_CONTENT_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):POLICY_LEVEL_3_NAME AS POLICY_LEVEL_3_NAME,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):POLICY_LEVEL_2_REFERENCE AS POLICY_LEVEL_2_REFERENCE,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):CONTROL_STANDARD_REQUIREMENTS AS CONTROL_STANDARD_REQUIREMENTS,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):AUTHORITATIVE_SOURCES AS AUTHORITATIVE_SOURCES
FROM ARCHER_CONTENT_POLICIES_POLICY_LEVEL_3_RAW
ORDER BY CONTENT_ID
LIMIT 100;

-- 7. Authoritative Source: Standard memberships on the publication root.
SELECT CONTENT_ID AS SOURCE_CONTENT_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):SOURCE_NAME AS SOURCE_NAME,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):TOPIC_REFERENCES AS TOPIC_REFERENCES,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):CONTROL_STANDARDS AS CONTROL_STANDARDS
FROM ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SOURCE_RAW
ORDER BY CONTENT_ID
LIMIT 100;

-- 8. Topic: reverse parent reference to its Source, plus Standard memberships.
SELECT CONTENT_ID AS TOPIC_CONTENT_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):TOPIC_NAME AS TOPIC_NAME,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):SOURCE_REFERENCES AS SOURCE_REFERENCES,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):CONTROL_STANDARDS AS CONTROL_STANDARDS
FROM ARCHER_CONTENT_AUTHORITATIVE_SOURCES_TOPIC_RAW
ORDER BY CONTENT_ID
LIMIT 100;

-- 9. Section: reverse parent reference to its Topic, plus Standard memberships.
SELECT CONTENT_ID AS SECTION_CONTENT_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):SECTION_NAME AS SECTION_NAME,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):TOPIC_REFERENCES AS TOPIC_REFERENCES,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):CONTROL_STANDARDS AS CONTROL_STANDARDS
FROM ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SECTION_RAW
ORDER BY CONTENT_ID
LIMIT 100;

-- 10. Subsection: reverse parent reference to its Section, plus Standard memberships.
SELECT CONTENT_ID AS SUBSECTION_CONTENT_ID,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):SUB_SECTION_NAME AS SUB_SECTION_NAME,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):SECTION_REFERENCES AS SECTION_REFERENCES,
       TRY_PARSE_JSON(CURATED_JSON::VARCHAR):CONTROL_STANDARDS AS CONTROL_STANDARDS
FROM ARCHER_CONTENT_AUTHORITATIVE_SOURCES_SUB_SECTION_RAW
ORDER BY CONTENT_ID
LIMIT 100;
